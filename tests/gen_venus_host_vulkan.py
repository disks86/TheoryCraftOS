# Writes tests/VenusHostVulkan.inc: for each function of the kernel's Vulkan table (TCOS_KVK_PROCS in src/Graphics/Graphics3D/Venus/KernelVulkan.h), a trampoline
# into the build host's Vulkan loader, and fill_table() that puts them in the table (VenusHostTest.cpp). Run after changing the list.
import re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
header = open(os.path.join(root, 'src/Graphics/Graphics3D/Venus/KernelVulkan.h')).read()
procs = re.findall(r'X\((\w+)\)', header[header.index('#define TCOS_KVK_PROCS'):header.index('typedef struct TcosKernelVulkan')])
core = open(os.path.join(root, 'src/Vulkan/khronos/vulkan/vulkan_core.h')).read()
out = ['/* Generated by tests/gen_venus_host_vulkan.py from KernelVulkan.h and vulkan_core.h: do not edit. */']
for p in procs:
    if p == 'CreateInstance':
        continue
    m = re.search(r'VKAPI_ATTR (\w+) VKAPI_CALL vk' + p + r'\(\s*(.*?)\);', core, re.S)
    if not m:
        sys.exit('no prototype for vk' + p)
    ret, params = m.group(1), ' '.join(m.group(2).split())
    names = [re.split(r'[\s\*]+', a.strip().split('[')[0])[-1] for a in params.split(',')] if params != 'void' else []
    out.append('namespace { TRAMPOLINE(%s, %s, (%s), (%s)) }' % (p, ret, params, ', '.join(names)))
out.append('static void fill_table(TcosKernelVulkan* t) {')
for p in procs:
    out.append('  t->%s = t_%s;' % (p, p))
out.append('}')
open(os.path.join(root, 'tests/VenusHostVulkan.inc'), 'w').write('\n'.join(out) + '\n')
