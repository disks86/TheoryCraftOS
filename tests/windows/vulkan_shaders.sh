#!/usr/bin/env bash
# Regenerates tests/windows/vulkantest_shaders.h from tests/data/spirv/vk_*.{vert,frag} and cs_*.comp (needs glslc).
set -euo pipefail
cd "$(dirname "$0")/../data/spirv"
for f in vk_tri.vert vk_tri.frag vk_tex.frag vk_push.vert vk_flat.frag vk_cubetex.frag vk_vtexdraw.vert; do glslc --target-env=vulkan1.0 -O "$f" -o "$f.spv"; done
for f in cs_add cs_shared cs_big cs_ctex; do glslc --target-env=vulkan1.0 -O "$f.comp" -o "${f}_opt.comp.spv"; done
python3 - <<'PY'
import struct
out = "/* Generated by tests/windows/vulkan_shaders.sh from tests/data/spirv/vk_*.{vert,frag} and cs_*.comp (glslc). */\n"
for name, var in [("vk_tri.vert.spv", "tri_vert"), ("vk_tri.frag.spv", "tri_frag"), ("vk_tex.frag.spv", "tex_frag"), ("vk_push.vert.spv", "push_vert"), ("vk_flat.frag.spv", "flat_frag"), ("vk_cubetex.frag.spv", "cubetex_frag"), ("vk_vtexdraw.vert.spv", "vtexdraw_vert"), ("cs_ctex_opt.comp.spv", "ctex_comp"),
                  ("cs_add_opt.comp.spv", "add_comp"), ("cs_shared_opt.comp.spv", "shared_comp"), ("cs_big_opt.comp.spv", "big_comp")]:
    d = open(name, "rb").read()
    w = struct.unpack("<%dI" % (len(d) // 4), d)
    out += "static const unsigned %s[] = {\n" % var
    for i in range(0, len(w), 8):
        out += "  " + ", ".join("0x%08x" % x for x in w[i:i + 8]) + ",\n"
    out += "};\n"
open("../../windows/vulkantest_shaders.h", "w").write(out)
PY
