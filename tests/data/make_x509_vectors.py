#!/usr/bin/env python3
"""Writes tests/X509Vectors.inc: certificate chains built with Python's cryptography package (OpenSSL), good and bad, for
tests/X509Test.cpp. The keys are generated on each run; the dates are fixed around 2026-10-17 (the test's "now")."""
import datetime, os, ipaddress
from cryptography import x509
from cryptography.x509.oid import NameOID, ExtendedKeyUsageOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa, padding

UTC = datetime.timezone.utc
NOW = datetime.datetime(2026, 10, 17, 12, 0, 0, tzinfo=UTC)
out = ["// Generated by tests/data/make_x509_vectors.py - do not edit.\n"]
names = []

def der(c): return c.public_bytes(serialization.Encoding.DER).hex()
def key_rsa(bits=2048): return rsa.generate_private_key(65537, bits)
def key_ec(curve=ec.SECP256R1()): return ec.generate_private_key(curve)

def make(cn, key, issuer=None, issuer_key=None, ca=False, pathlen=None, sans=(), ips=(), eku=None, key_usage="auto", not_before=None, not_after=None,
         hash_alg=None, pss=False, critical_unknown=False, basic=True):
    subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
    b = (x509.CertificateBuilder().subject_name(subject).issuer_name(issuer.subject if issuer else subject).public_key(key.public_key())
         .serial_number(x509.random_serial_number()).not_valid_before(not_before or NOW - datetime.timedelta(days=100))
         .not_valid_after(not_after or NOW + datetime.timedelta(days=3000)))
    if basic: b = b.add_extension(x509.BasicConstraints(ca=ca, path_length=pathlen), critical=True)
    if key_usage == "auto":
        key_usage = x509.KeyUsage(digital_signature=not ca, content_commitment=False, key_encipherment=False, data_encipherment=False, key_agreement=False,
                                  key_cert_sign=ca, crl_sign=ca, encipher_only=False, decipher_only=False)
    if key_usage: b = b.add_extension(key_usage, critical=True)
    gn = [x509.DNSName(s) for s in sans] + [x509.IPAddress(ipaddress.ip_address(i)) for i in ips]
    if gn: b = b.add_extension(x509.SubjectAlternativeName(gn), critical=False)
    if eku: b = b.add_extension(x509.ExtendedKeyUsage(eku), critical=False)
    b = b.add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False)
    if issuer_key is not None: b = b.add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(issuer_key.public_key()), critical=False)
    if critical_unknown: b = b.add_extension(x509.UnrecognizedExtension(x509.ObjectIdentifier("1.3.6.1.4.1.99999.1"), b"\x05\x00"), critical=True)
    signer = issuer_key or key
    if hash_alg is None: hash_alg = hashes.SHA384() if isinstance(signer, ec.EllipticCurvePrivateKey) and signer.curve.key_size == 384 else hashes.SHA256()
    if pss and isinstance(signer, rsa.RSAPrivateKey):
        # sign with PSS through the builder's rsa_padding
        return b.sign(signer, hash_alg, rsa_padding=padding.PSS(padding.MGF1(hash_alg), hash_alg.digest_size))
    return b.sign(signer, hash_alg)

def chain(name, certs):
    names.append(name)
    out.append("static const char* const k%s[] = {%s};\n" % (name, ", ".join('"%s"' % der(c) for c in certs)))

def root(cn, key, **kw): return make(cn, key, ca=True, **kw)

# --- good chains
rk = key_rsa(); r = root("Test Root RSA", rk)
ik = key_ec(ec.SECP384R1()); i = make("Test Intermediate P384", ik, r, rk, ca=True, pathlen=0)
lk = key_ec(); leaf = make("printer.example.com", lk, i, ik, sans=["printer.example.com", "*.lab.example.com"], ips=["10.0.0.2"], eku=[ExtendedKeyUsageOID.SERVER_AUTH])
chain("ChainA", [leaf, i, r]); chain("ChainARoot", [r]); chain("ChainAIntermediate", [i])
chain("ChainALeafOnly", [leaf])
# root EC, intermediate RSA signed by EC, leaf RSA signed with PSS
rk2 = key_ec(); r2 = root("Test Root EC", rk2)
ik2 = key_rsa(3072); i2 = make("Test Intermediate RSA", ik2, r2, rk2, ca=True)
lk2 = key_rsa(); leaf2 = make("www.example.org", lk2, i2, ik2, sans=["www.example.org"], pss=True, hash_alg=hashes.SHA384())
chain("ChainB", [leaf2, i2, r2]); chain("ChainBRoot", [r2])
# intermediates out of order and an unrelated extra certificate
chain("ChainAShuffled", [leaf, r2, i]);
# --- bad
chain("Expired", [make("old.example.com", lk, i, ik, sans=["old.example.com"], not_before=NOW - datetime.timedelta(days=400), not_after=NOW - datetime.timedelta(days=1)), i, r])
chain("NotYetValid", [make("new.example.com", lk, i, ik, sans=["new.example.com"], not_before=NOW + datetime.timedelta(days=2), not_after=NOW + datetime.timedelta(days=100)), i, r])
other = key_rsa(); other_root = root("Test Root RSA", other)   # the same name as the real root, another key
chain("WrongIssuerKey", [leaf, i, other_root]); chain("OtherRoot", [other_root])
nk = key_ec(); not_ca = make("Test Intermediate P384", nk, r, rk, ca=False, key_usage=None)   # intermediate without CA bit
chain("NotCa", [make("x.example.com", lk, not_ca, nk, sans=["x.example.com"]), not_ca, r])
p0k = key_ec(); p0 = make("Pathlen Zero", p0k, r, rk, ca=True, pathlen=0)
sub_k = key_ec(); sub = make("Below Pathlen Zero", sub_k, p0, p0k, ca=True)
chain("PathLen", [make("deep.example.com", lk, sub, sub_k, sans=["deep.example.com"]), sub, p0, r])
nu = key_ec(); no_cert_sign = make("No CertSign", nu, r, rk, ca=True, key_usage=x509.KeyUsage(True, False, False, False, False, False, False, False, False))
chain("NoKeyCertSign", [make("y.example.com", lk, no_cert_sign, nu, sans=["y.example.com"]), no_cert_sign, r])
chain("CriticalUnknown", [make("crit.example.com", lk, i, ik, sans=["crit.example.com"], critical_unknown=True), i, r])
chain("ClientAuthOnly", [make("client.example.com", lk, i, ik, sans=["client.example.com"], eku=[ExtendedKeyUsageOID.CLIENT_AUTH]), i, r])
def der_len(n): return bytes([n]) if n < 128 else (bytes([0x81, n]) if n < 256 else bytes([0x82, n >> 8, n & 255]))
def tlv(tag, body): return bytes([tag]) + der_len(len(body)) + body
def sha1_resign(c, signer_key):
    # the SHA-256 certificate re-encoded as sha1WithRSAEncryption (the OIDs differ in the last byte) and signed again; the library refuses to sign with SHA-1
    old = bytes.fromhex("2a864886f70d01010b"); new = bytes.fromhex("2a864886f70d010105")
    tbs = c.tbs_certificate_bytes
    assert old in tbs
    tbs = tbs.replace(old, new)
    sig = signer_key.sign(tbs, padding.PKCS1v15(), hashes.SHA1())
    alg = tlv(0x30, tlv(0x06, new) + tlv(0x05, b""))
    return tlv(0x30, tbs + alg + tlv(0x03, b"\0" + sig))
names.append("Sha1Signed")
out.append('static const char* const kSha1Signed[] = {"%s", "%s"};\n' % (sha1_resign(make("sha1.example.com", lk, r, rk, sans=["sha1.example.com"]), rk).hex(), der(r)))
chain("Rsa1024Leaf", [make("weak.example.com", key_rsa(1024), r, rk, sans=["weak.example.com"]), r])
sk = key_ec(); selfsigned = make("selfsigned.example.com", sk, sans=["selfsigned.example.com"], ca=False, basic=False)
chain("SelfSigned", [selfsigned]); chain("SelfSignedAnchor", [selfsigned])
chain("CaAsLeafAnchor", [r])   # a root presented on its own and trusted as it is
# a certificate with a bad signature (a byte of the leaf's signature flipped)
bad = bytearray(leaf.public_bytes(serialization.Encoding.DER)); bad[-5] ^= 0x01
out.append('static const char* const kTamperedSignature[] = {"%s", "%s", "%s"};\n' % (bytes(bad).hex(), der(i), der(r)))
bad = bytearray(leaf.public_bytes(serialization.Encoding.DER)); bad[len(bad) // 2] ^= 0x40
out.append('static const char* const kTamperedBody[] = {"%s", "%s", "%s"};\n' % (bytes(bad).hex(), der(i), der(r)))
# a leaf with no SAN
chain("NoSan", [make("nosan.example.com", lk, i, ik), i, r])
# time conversion pairs
pairs = [(1970, 1, 1, 0, 0, 0), (2000, 2, 29, 23, 59, 59), (2026, 10, 17, 12, 0, 0), (2038, 1, 19, 3, 14, 8), (2100, 3, 1, 0, 0, 0), (1999, 12, 31, 23, 59, 59), (2049, 12, 31, 23, 59, 59)]
out.append("struct TimePair { unsigned y, mo, d, h, mi, s; unsigned long long t; };\nstatic const TimePair kTimePairs[] = {\n")
for p in pairs:
    out.append("  {%d, %d, %d, %d, %d, %d, %dull},\n" % (*p, int(datetime.datetime(*p, tzinfo=UTC).timestamp())))
out.append("};\n")
out.append("static const unsigned long long kNow = %dull;\n" % int(NOW.timestamp()))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "X509Vectors.inc"), "w").write("".join(out))
