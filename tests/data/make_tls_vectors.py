#!/usr/bin/env python3
"""Writes tests/TlsVectors.inc: what real TLS servers (`openssl s_server`) sent to our TlsSocket client, recorded once, for tests/TlsReplayTest.cpp
to play back. The client is deterministic (tests/TlsDeterministic.hpp seeds its randomness), so the second time it makes the same ClientHello and
key shares and the recorded answer fits it. Changing anything in the ClientHello therefore means running this script again (it needs openssl and
a C++ compiler; certificates and server keys are new on every run). Usage: tests/data/make_tls_vectors.py"""
import os, re, subprocess, sys, time, tempfile, hashlib, random

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
work = tempfile.mkdtemp(prefix="tcos-tlsvec-")
tool = os.path.join(work, "TlsLive")
subprocess.check_call(["g++", "-std=c++20", "-O1", "-I", root + "/src", "-I", root + "/tests", root + "/tests/TlsLive.cpp", root + "/tests/KernelStubs.cpp", root + "/src/Kernel/Sync.cpp"]
                      + [os.path.join(root, "src/Network/Tls", f) for f in ("TlsSocket.cpp", "TlsKeys.cpp", "TlsCertificate.cpp", "TlsSession.cpp")]
                      + [os.path.join(root, "src/Network/Ipp", f) for f in os.listdir(root + "/src/Network/Ipp") if f.endswith(".cpp")] + [root + "/src/Hardware/Printer/IppPrinter.cpp"]
                      + [os.path.join(root, "src/Crypto", f) for f in os.listdir(root + "/src/Crypto") if f.endswith(".cpp")] + ["-o", tool])

def sh(*a, **k): return subprocess.run(a, cwd=work, capture_output=True, **k)
def make_ca(name, *keyspec):
    sh("openssl", "req", "-x509", "-newkey", *keyspec, "-nodes", "-keyout", name + "-ca.key", "-out", name + "-ca.pem", "-days", "30", "-subj", "/CN=Test CA " + name,
       "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign,cRLSign")
def make_server(name, *keyspec):
    sh("openssl", "req", "-newkey", *keyspec, "-nodes", "-keyout", name + "-srv.key", "-out", name + "-srv.csr", "-subj", "/CN=localhost")
    open(os.path.join(work, name + ".ext"), "w").write("subjectAltName=DNS:localhost,IP:127.0.0.1\nbasicConstraints=CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n")
    sh("openssl", "x509", "-req", "-in", name + "-srv.csr", "-CA", name + "-ca.pem", "-CAkey", name + "-ca.key", "-CAcreateserial", "-out", name + "-srv.pem", "-days", "30", "-extfile", name + ".ext")
make_ca("rsa", "rsa:2048"); make_server("rsa", "rsa:2048")
make_ca("p256", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1"); make_server("p256", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1")
make_ca("p384", "ec", "-pkeyopt", "ec_paramgen_curve:secp384r1"); make_server("p384", "ec", "-pkeyopt", "ec_paramgen_curve:secp384r1")

now = int(time.time()) + 30
# name, certificate, server arguments, client arguments, server stdin script (key updates)
cases = [
    ("Tls13ChaChaRsa",    "rsa",  "-www -tls1_3 -ciphersuites TLS_CHACHA20_POLY1305_SHA256", "--tls13", None),
    ("Tls13Aes128P256",   "p256", "-www -tls1_3 -ciphersuites TLS_AES_128_GCM_SHA256", "--tls13", None),
    ("Tls13Aes256P384",   "p384", "-www -tls1_3 -ciphersuites TLS_AES_256_GCM_SHA384", "--tls13", None),
    ("Tls13RetryRequest", "p384", "-www -tls1_3 -groups P-384 -ciphersuites TLS_AES_256_GCM_SHA384", "--tls13", None),
    ("Tls13KeyUpdate",    "rsa",  "-tls1_3 -ciphersuites TLS_AES_128_GCM_SHA256", "--tls13 --hold 4", [(0.8, "A\n"), (1.0, "K\n"), (0.4, "B\n"), (1.0, "k\n"), (0.4, "C\n"), (1.5, "")]),
    ("Tls12RsaAes128",    "rsa",  "-www -tls1_2 -cipher ECDHE-RSA-AES128-GCM-SHA256", "--tls12", None),
    ("Tls12RsaChaCha",    "rsa",  "-www -tls1_2 -cipher ECDHE-RSA-CHACHA20-POLY1305", "--tls12", None),
    ("Tls12EcdsaAes256",  "p384", "-www -tls1_2 -cipher ECDHE-ECDSA-AES256-GCM-SHA384", "--tls12", None),
    ("Tls12EcdsaP256Kx",  "p256", "-www -tls1_2 -cipher ECDHE-ECDSA-AES128-GCM-SHA256 -groups P-256", "--tls12", None),
    ("Tls12EcdsaP384Kx",  "p256", "-www -tls1_2 -cipher ECDHE-ECDSA-AES256-GCM-SHA384 -groups P-384", "--tls12", None),
    ("Tls12CbcEtm",       "rsa",  "-www -tls1_2 -cipher ECDHE-RSA-AES128-SHA", "--tls12", None),
    ("Tls12CbcNoEtm",     "p384", "-www -tls1_2 -no_etm -cipher ECDHE-ECDSA-AES256-SHA384", "--tls12", None),
]
out = ["// Generated by tests/data/make_tls_vectors.py - do not edit.\n",
       "struct TlsVector { const char* name; unsigned seed; unsigned long long now; const char* ca_pem; const char* server_stream; const char* plaintext; const char* suite; unsigned version; };\n",
       "static const TlsVector kTlsVectors[] = {\n"]
port = 26000 + random.randrange(2000)
for i, (name, cert, sargs, cargs, script) in enumerate(cases):
    port += 1
    dump = os.path.join(work, name + ".dump"); plain = os.path.join(work, name + ".plain")
    for f in (dump, plain):
        if os.path.exists(f): os.remove(f)
    srv = subprocess.Popen(["openssl", "s_server", "-accept", str(port), "-cert", cert + "-srv.pem", "-key", cert + "-srv.key"] + sargs.split(), cwd=work,
                           stdin=subprocess.PIPE if script else subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(0.5)
    env = dict(os.environ, TLS_DUMP=dump)
    client = subprocess.Popen([tool, "127.0.0.1", str(port), "--name", "localhost", "--ca", cert + "-ca.pem", "--seed", str(100 + i), "--now", str(now), "--dump-plain", plain] + cargs.split(),
                              cwd=work, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if script:
        for delay, text in script:
            time.sleep(delay)
            if text: srv.stdin.write(text.encode()); srv.stdin.flush()
    text, _ = client.communicate(timeout=60)
    srv.kill(); srv.wait()
    m = re.search(r"handshake ok: version 0x([0-9a-f]+), (\w+)", text)
    if not m or client.returncode != 0: sys.exit("case %s failed:\n%s" % (name, text))
    stream = open(dump, "rb").read(); data = open(plain, "rb").read()
    pem = open(os.path.join(work, cert + "-ca.pem")).read()
    out.append('  {"%s", %d, %dull, "%s", "%s", "%s", "%s", 0x%s},\n' % (name, 100 + i, now, pem.replace("\n", "\\n"), stream.hex(), data.hex(), m.group(2), m.group(1)))
    print("recorded %-18s %-40s %6d bytes from the server, %5d bytes of application data" % (name, m.group(2), len(stream), len(data)))
out.append("};\n")
open(os.path.join(root, "tests", "TlsVectors.inc"), "w").write("".join(out))
