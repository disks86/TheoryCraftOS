  const std::string gs = listing(k_gs_copy_dxbc, sizeof k_gs_copy_dxbc);
  CHECK(contains(gs, "\ngs_4_0\n"));
  CHECK(contains(gs, "dcl_inputprimitive triangle"));
  CHECK(contains(gs, "dcl_outputtopology trianglestrip"));
  CHECK(contains(gs, "dcl_maxout 6"));
  CHECK(contains(gs, "dcl_input_siv v[3][0].xyzw, position"));
  CHECK(contains(gs, "mov o0.xyzw, v[0][0].xyzw"));
  CHECK(contains(gs, "emit"));
  const std::string smp = listing(k_ps_sample_dxbc, sizeof k_ps_sample_dxbc);
  CHECK(contains(smp, "dcl_sampler s0, mode_default"));
  CHECK(contains(smp, "dcl_resource_texture2d (float,float,float,float) t0"));
  CHECK(contains(smp, "sample "));
  if (std::getenv("DXBC_REFLECT_SHOW")) std::printf("%s\n%s\n%s\n", ps.c_str(), gs.c_str(), smp.c_str());
  // colour coding is an HTML page
  DxdText h = {0, 0, 0, 0, 1};
