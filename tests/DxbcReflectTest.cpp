static std::string preprocess(const char *source, bool *ok, std::string *errors = nullptr, const HppIo *io = nullptr, const char *define = nullptr) {
  DxdText out = {0, 0, 0, 0, 0}, err = {0, 0, 0, 0, 0};
  const char *names[1] = {define}, *values[1] = {nullptr};
  *ok = hpp_run(source, std::strlen(source), "test.hlsl", names, values, define ? 1 : 0, io, &out, &err) != 0;
  std::string s = out.data ? std::string(out.data, out.size) : std::string();
  if (errors) *errors = err.data ? std::string(err.data, err.size) : std::string();
  free(out.data);
  free(err.data);
  return s;
}
static int open_include(void *, int system, const char *name, const char *, const char **data, size_t *bytes) {
  static const char a[] = "float from_a;\n#define FROM_A 7\n";
  static const char b[] = "#include \"a.h\"\nfloat from_b = FROM_A;\n";
  if (!std::strcmp(name, "a.h")) { *data = a; *bytes = sizeof a - 1; return 1; }
  if (!std::strcmp(name, "b.h") && system) { *data = b; *bytes = sizeof b - 1; return 1; }
  if (!std::strcmp(name, "self.h")) { *data = "#include \"self.h\"\n"; *bytes = 18; return 1; }
  return 0;
}
static int g_closes;
static void close_include(void *, const char *) { ++g_closes; }

static void test_preprocessor() {
  bool ok;
  std::string e;
  std::string s = preprocess("#define A 1\n#define F(x, y) ((x) + (y) * A)\nfloat v = F(2, 3);\n", &ok);
  CHECK(ok && contains(s, "float v = ((2) + (3) * 1);"));
  s = preprocess("#define S(x) #x\n#define J(a, b) a ## b\nS(hello \"w\") J(foo, bar) J(1, 2)\n", &ok);
  CHECK(ok && contains(s, "\"hello \\\"w\\\"\" foobar 12"));
  s = preprocess("#if 1 + 2 * 3 == 7 && !defined(B) && (4 >> 1) == 2\nyes\n#else\nno\n#endif\n", &ok);
  CHECK(ok && contains(s, "yes") && !contains(s, "no"));
  s = preprocess("#ifdef X\nx\n#elif defined X || 0x10 == 16\nhex\n#else\nnone\n#endif\n", &ok);
  CHECK(ok && contains(s, "hex") && !contains(s, "none"));
  s = preprocess("#ifndef X\n#define X\n#endif\n#ifdef X\nhas\n#endif\n", &ok);
  CHECK(ok && contains(s, "has"));
  s = preprocess("float a; // comment\nfloat /* inline */ b;\n/* over\nlines */ float c;\n", &ok);
  CHECK(ok && !contains(s, "comment") && !contains(s, "inline") && contains(s, "float c;"));
  s = preprocess("#define LONG 1 + \\\n 2\nint x = LONG;\n", &ok);
  CHECK(ok && contains(s, "int x = 1 +  2;"));
  s = preprocess("#define R R + 1\nint r = R;\n", &ok);      // (a macro is not expanded inside itself)
  CHECK(ok && contains(s, "int r = R + 1;"));
  s = preprocess("#define V(...) f(__VA_ARGS__)\nV(1, 2, 3)\n", &ok);
  CHECK(ok && contains(s, "f(1, 2, 3)"));
  s = preprocess("#define M(a) [a]\nM(\n  x\n)\n", &ok);      // (a call over lines)
  CHECK(ok && contains(s, "[x]"));
  s = preprocess("#pragma pack_matrix(row_major)\n", &ok);
  CHECK(ok && contains(s, "#pragma pack_matrix(row_major)"));
  s = preprocess("a __LINE__\nb __LINE__\n", &ok);
  CHECK(ok && contains(s, "a 1") && contains(s, "b 2"));
  s = preprocess("#line 40 \"other.hlsl\"\nx __LINE__ __FILE__\n", &ok);
  CHECK(ok && contains(s, "#line 40 \"other.hlsl\"") && contains(s, "x 40 \"other.hlsl\""));
  s = preprocess("float f = D;\n", &ok, nullptr, nullptr, "D");
  CHECK(ok && contains(s, "float f = 1;"));
  // errors
  preprocess("#error stop here\n", &ok, &e);
  CHECK(!ok && contains(e, "test.hlsl(1): error: #error: stop here"));
  preprocess("#if 1\nx\n", &ok, &e);
  CHECK(!ok && contains(e, "unterminated"));
  preprocess("#endif\n", &ok, &e);
  CHECK(!ok);
  preprocess("#if 1 /\n#endif\n", &ok, &e);
  CHECK(!ok);
  preprocess("#if 1 / 0\n#endif\n", &ok, &e);
  CHECK(!ok && contains(e, "division"));
  preprocess("#frobnicate\n", &ok, &e);
  CHECK(!ok && contains(e, "invalid preprocessor directive"));
  preprocess("#define F(a) a\nF(1, 2)\n", &ok, &e);
  CHECK(!ok && contains(e, "wrong number"));
  preprocess("#include \"a.h\"\n", &ok, &e);      // (no opener)
  CHECK(!ok && contains(e, "failed to open include file"));
  // includes
  const HppIo io = {nullptr, open_include, close_include};
  g_closes = 0;
  s = preprocess("#include <b.h>\nint z = FROM_A;\n", &ok, &e, &io);
  CHECK(ok && contains(s, "float from_a;") && contains(s, "float from_b = 7;") && contains(s, "int z = 7;") && contains(s, "#line 1 \"b.h\"") &&
        contains(s, "#line 2 \"test.hlsl\""));
  CHECK(g_closes == 2);
  preprocess("#include \"self.h\"\n", &ok, &e, &io);      // (an include of itself ends at the depth limit)
  CHECK(!ok && contains(e, "nested too deeply"));
  // truncations and changed bytes of a text: nothing read past it
  const char text[] = "#define F(x, y) x ## y #y\n#if defined(F) && (1 << 3) > 2 ? 1 : 0\nF(a, b) \"str\\\"\" 'c'\n#else\n#error no\n#endif\n/* tail */\n";
  for (size_t n = 0; n < sizeof text; ++n) {
    std::vector<char> part(text, text + n);
    DxdText out = {0, 0, 0, 0, 0}, err = {0, 0, 0, 0, 0};
    hpp_run(part.data(), n, nullptr, nullptr, nullptr, 0, &io, &out, &err);
    free(out.data);
    free(err.data);
    for (size_t at = 0; at < n; ++at) {
      const char keep = part[at];
      for (char c : {'(', ')', '#', '"', '\\', '\n', '/', '*'}) {
        part[at] = c;
        DxdText o2 = {0, 0, 0, 0, 0}, e2 = {0, 0, 0, 0, 0};
        hpp_run(part.data(), n, "x", nullptr, nullptr, 0, &io, &o2, &e2);
        free(o2.data);
        free(e2.data);
      }
      part[at] = keep;
    }
  }
}

// The fixtures of tests/data/dxbc that are there (in a checkout without Git LFS's files they are pointers, and left out).
static void test_fixture_folder() {
  const char *dir = std::getenv("DXBC_FIXTURES");
  const std::filesystem::path folder = dir ? dir : "tests/data/dxbc";
  int seen = 0, checked_sums = 0;
  std::error_code ec;
  for (const auto &entry : std::filesystem::directory_iterator(folder, ec)) {
    if (entry.path().extension() != ".dxbc") continue;
    std::ifstream f(entry.path(), std::ios::binary);
    std::vector<uint8_t> d((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    if (d.size() < 32 || dxr_u32(d.data()) != DXR_DXBC) continue;
    ++seen;
    size_t total;
    uint32_t n;
    CHECK(dxr_container(d.data(), d.size(), &total, &n));
    // (a checksum of zeros: a container this project's tools put together, not the compiler)
    if (dxr_u32(d.data() + 4) | dxr_u32(d.data() + 8) | dxr_u32(d.data() + 12) | dxr_u32(d.data() + 16)) {
      uint32_t sum[4];
      dxr_checksum(d.data(), total, sum);
      const bool same = sum[0] == dxr_u32(d.data() + 4) && sum[1] == dxr_u32(d.data() + 8) && sum[2] == dxr_u32(d.data() + 12) && sum[3] == dxr_u32(d.data() + 16);
      // (a fixture this project changed after the compiler made it - gs_copy_inst2 - keeps the old checksum: said, not counted against the reader)
      if (!same) std::printf("checksum differs (changed after compiling?): %s\n", entry.path().filename().c_str());
      else ++checked_sums;
    }
    const uint8_t *code;
    size_t words;
    int shex;
    const bool compiled = dxr_u32(d.data() + 4) != 0;      // (a container this project's tools put together may have parts the compiler leaves out)
    if (compiled && dxr_code(d.data(), d.size(), &code, &words, &shex)) {
      const std::string text = listing(d.data(), d.size());
      CHECK(!text.empty());
      if (contains(text, "(truncated)") || contains(text, "the code ends inside")) std::printf("listing incomplete: %s\n", entry.path().filename().c_str());
      CHECK(!contains(text, "(truncated)") && !contains(text, "the code ends inside"));
      if (std::getenv("DXBC_REFLECT_SHOW_ALL")) std::printf("== %s\n%s", entry.path().filename().c_str(), text.c_str());
    }
    if (seen <= 40) abuse(d.data(), d.size(), entry.path().filename().c_str());
    else walk(d.data(), d.size());
  }
  std::printf("fixtures: %d containers read, %d checksums the same as the compiler's\n", seen, checked_sums);
}

