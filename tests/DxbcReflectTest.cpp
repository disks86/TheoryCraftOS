static void test_float_text() {
  auto text = [](float f) {
    uint32_t bits;
    std::memcpy(&bits, &f, 4);
    DxdText t = {0, 0, 0, 0, 0};
    dxd_float_bits(&t, bits);
    std::string s(t.data, t.size);
    free(t.data);
    return s;
  };
  CHECK(text(1.0f) == "1.000000");
  CHECK(text(0.5f) == "0.500000");
  CHECK(text(-2.25f) == "-2.250000");
  CHECK(text(0.3f) == "0.300000");
  CHECK(text(1.6f) == "1.600000");
  CHECK(text(1e-7f) == "0.000000");
  CHECK(text(123456.0f) == "123456.000000");
}

