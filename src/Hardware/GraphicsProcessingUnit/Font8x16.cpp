// Symbols and punctuation outside the letter ranges, as an ASCII look-alike.
char look_alike(char32_t c) {
  switch (c) {
    case 0xA0: return ' ';
    case 0xA1: return '!';
    case 0xA2: return 'c';
    case 0xA3: return 'L';
    case 0xA5: return 'Y';
    case 0xA7: return 'S';
    case 0xA9: return 'C';
    case 0xAB: return '<';
    case 0xAD: return '-';
    case 0xAE: return 'R';
    case 0xB0: return 'o';
    case 0xB1: return '+';
    case 0xB2: return '2';
    case 0xB3: return '3';
    case 0xB4: return '\'';
    case 0xB5: return 'u';
    case 0xB7: return '.';
    case 0xB9: return '1';
    case 0xBB: return '>';
    case 0xBF: return '?';
    case 0x2010: case 0x2011: case 0x2012: case 0x2013: case 0x2014: case 0x2212: return '-';
    case 0x2018: case 0x2019: case 0x201A: case 0x2032: return '\'';
    case 0x201C: case 0x201D: case 0x201E: case 0x2033: return '"';
    case 0x2022: case 0x2023: case 0x25CF: return '*';
    case 0x2026: return '.';
    case 0x2039: return '<';
    case 0x203A: return '>';
    case 0x20AC: return 'E';
    case 0x2122: return 'T';
    default: return 0;
  }
}

