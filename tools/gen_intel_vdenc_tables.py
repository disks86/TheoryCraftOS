#!/usr/bin/env python3
"""Generates src/Hardware/VideoCodec/Intel/IntelVdencTables.inc: the mode, motion vector and HME cost tables and the adaptive inter rounding table the Intel media driver
(MIT licence) programs into VDEnc H.264 encodes on Gen9.

usage: gen_intel_vdenc_tables.py <codechal_vdenc_avc.cpp> <codechal_vdenc_avc_g9_kbl.cpp> <out.inc>
"""
import re, sys

def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    return re.sub(r'//[^\n]*', '', t)

def parse_braces(t, pos):
    """t[pos] is '{'. Returns (nested list, position after the matching '}')."""
    out, pos, num = [], pos + 1, ''
    while True:
        c = t[pos]
        if c == '{':
            sub, pos = parse_braces(t, pos)
            out.append(sub)
            continue
        if c in ',}' :
            if num.strip(): out.append(int(num.strip()))
            num = ''
            pos += 1
            if c == '}': return out, pos
            continue
        num += c
        pos += 1

def flatten(node, dims):
    """Pads an initialiser list the way C does (missing entries are zero)."""
    out = []
    for k in range(dims[0]):
        item = node[k] if k < len(node) else None
        if len(dims) == 1:
            out.append(item if isinstance(item, int) else 0)
        else:
            out.extend(flatten(item if isinstance(item, list) else [], dims[1:]))
    return out

def array(src, name, dims):
    m = re.search(r'%s\s*(\[[^\]]*\]\s*)+=\s*\{' % re.escape(name), src)
    if not m: raise SystemExit('table %s not found' % name)
    node, _ = parse_braces(strip_comments(src), len(strip_comments(src[:m.end() - 1])))
    return flatten(node, dims)

def emit(o, ctype, cname, dims, nums):
    o.append('constexpr %s %s%s = {' % (ctype, cname, ''.join('[%d]' % d for d in dims)))
    def rec(level, off):
        if level == len(dims) - 1:
            return '{' + ', '.join(str(x) for x in nums[off:off + dims[level]]) + '}'
        step = 1
        for d in dims[level + 1:]: step *= d
        return '{' + ',\n '.join(rec(level + 1, off + k * step) for k in range(dims[level])) + '}'
    o[-1] = o[-1].replace(' = {', ' = ') + rec(0, 0) + ';'

def main():
    vdenc = open(sys.argv[1]).read()
    kbl = open(sys.argv[2]).read()
    o = ['// Generated by tools/gen_intel_vdenc_tables.py from the Intel media driver (MIT licence). Do not edit by hand.']
    emit(o, 'uint16_t', 'kAvcModeCost', [2, 12, 52], array(vdenc, 'AVC_Mode_Cost', [2, 12, 52]))
    emit(o, 'uint8_t', 'kAdaptiveInterRoundingPWithoutB', [52], array(vdenc, 'AdaptiveInterRoundingPWithoutB', [52]))
    emit(o, 'uint8_t', 'kMvCostSkipBiasQPel', [3, 8], array(kbl, 'MV_Cost_SkipBias_QPel', [3, 8]))
    emit(o, 'uint16_t', 'kHmeMvCost', [8, 52], array(kbl, 'HmeCost', [8, 52]))
    open(sys.argv[3], 'w').write('\n'.join(o) + '\n')

main()
