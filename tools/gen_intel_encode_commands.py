#!/usr/bin/env python3
"""Generates src/Hardware/VideoCodec/Intel/IntelEncodeCommandImages.inc from the Intel media driver's hardware command definitions
(media_driver/agnostic/gen9_kbl/hw/vdbox/mhw_vdbox_{vdenc,mfx}_hwcmd_g9_kbl.{h,cpp}).

For every command asked for it writes the command's default image (what the media driver's constructor sets) and a descriptor
{dword, low bit, high bit} for each named bit field, so the encoder code sets fields by name instead of by hand-counted shifts.

usage: gen_intel_encode_commands.py <vdenc.h> <vdenc.cpp> <mfx.h> <mfx.cpp> <out.inc>
"""
import re, sys

COMMANDS = [
    # (header, struct, short name)
    ('vdenc', 'VDENC_PIPE_MODE_SELECT', 'VdencPipeModeSelect'),
    ('vdenc', 'VDENC_SRC_SURFACE_STATE', 'VdencSrcSurfaceState'),
    ('vdenc', 'VDENC_REF_SURFACE_STATE', 'VdencRefSurfaceState'),
    ('vdenc', 'VDENC_DS_REF_SURFACE_STATE', 'VdencDsRefSurfaceState'),
    ('vdenc', 'VDENC_PIPE_BUF_ADDR_STATE', 'VdencPipeBufAddrState'),
    ('vdenc', 'VDENC_IMG_STATE', 'VdencImgState'),
    ('vdenc', 'VDENC_WALKER_STATE', 'VdencWalkerState'),
    ('vdenc', 'VD_PIPELINE_FLUSH', 'VdPipelineFlush'),
    ('vdenc', 'VDENC_CONST_QPT_STATE', 'VdencConstQptState'),
    ('vdenc', 'VDENC_WEIGHTSOFFSETS_STATE', 'VdencWeightsOffsetsState'),
    ('mfx', 'MFX_PIPE_MODE_SELECT', 'MfxPipeModeSelect'),
    ('mfx', 'MFX_SURFACE_STATE', 'MfxSurfaceState'),
    ('mfx', 'MFX_PIPE_BUF_ADDR_STATE', 'MfxPipeBufAddrState'),
    ('mfx', 'MFX_IND_OBJ_BASE_ADDR_STATE', 'MfxIndObjBaseAddrState'),
    ('mfx', 'MFX_BSP_BUF_BASE_ADDR_STATE', 'MfxBspBufBaseAddrState'),
    ('mfx', 'MFX_AVC_IMG_STATE', 'MfxAvcImgState'),
    ('mfx', 'MFX_AVC_SLICE_STATE', 'MfxAvcSliceState'),
    ('mfx', 'MFX_AVC_REF_IDX_STATE', 'MfxAvcRefIdxState'),
    ('mfx', 'MFX_PAK_INSERT_OBJECT', 'MfxPakInsertObject'),
    ('mfx', 'MFX_QM_STATE', 'MfxQmState'),
    ('mfx', 'MFX_FQM_STATE', 'MfxFqmState'),
]

def struct_text(header, name):
    m = re.search(r'^    struct %s_CMD\s*\n    \{' % re.escape(name), header, re.M)
    if not m:
        raise SystemExit('struct %s_CMD not found' % name)
    i = header.index('{', m.start())
    depth, j = 0, i
    while True:
        c = header[j]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    return header[i:j]

def parse_fields(text):
    """Top-level DWn unions -> {field: (dw, lo, hi)}, enum constants, dwSize."""
    fields = {}
    pend = []
    for line in text.split('\n'):
        f = re.search(r'uint32_t\s+(\w+)\s*:\s*__CODEGEN_BITFIELD\(\s*(\d+),\s*(\d+)\)', line)
        if f: pend.append((f.group(1), int(f.group(2)), int(f.group(3)))); continue
        m = re.match(r'^\s*\}\s*DW(\d+)\s*;', line)
        if m:
            dw = int(m.group(1))
            for n, lo, hi in pend:
                if not n.startswith('Reserved'): fields[n] = (dw, lo, hi)
            pend = []
        elif re.match(r'^\s*\}\s*\w+', line):
            pend = []
    enums = {}
    for e in re.finditer(r'^\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,', text, re.M):
        enums[e.group(1)] = int(e.group(2), 0)
    size = int(re.search(r'static const size_t dwSize = (\d+);', text).group(1))
    return fields, enums, size

def ctor_image(cpp, struct, fields, enums, size):
    m = re.search(r'%s_CMD::%s_CMD\(\)\s*\{' % (re.escape(struct), re.escape(struct)), cpp)
    img = [0] * size
    skipped = []
    if not m: return img, ['no constructor']
    j = cpp.index('}', m.end())
    # dword length helper used by constructors
    body = cpp[m.end():j]
    for line in body.split('\n'):
        a = re.match(r'\s*DW(\d+)\.(\w+)\s*=\s*(.+?);', line)
        if not a:
            if '=' in line and line.strip(): skipped.append(line.strip())
            continue
        dw, name, val = int(a.group(1)), a.group(2), a.group(3).strip()
        if name == 'Value':
            img[dw] = int(val, 0) if re.match(r'^(0x[0-9a-fA-F]+|\d+)$', val) else 0
            continue
        if name not in fields:
            skipped.append(line.strip()); continue
        d, lo, hi = fields[name]
        if val == 'GetOpLength(dwSize)': v = size - 2
        elif re.match(r'^(0x[0-9a-fA-F]+|\d+)$', val): v = int(val, 0)
        elif val in enums: v = enums[val]
        else:
            skipped.append(line.strip()); continue
        mask = ((1 << (hi - lo + 1)) - 1) << lo
        img[d] = (img[d] & ~mask) | ((v << lo) & mask)
    return img, skipped

def main():
    vh, vc, mh, mc, out = sys.argv[1:6]
    src = {'vdenc': (open(vh).read(), open(vc).read()), 'mfx': (open(mh).read(), open(mc).read())}
    o = []
    o.append('// Generated by tools/gen_intel_encode_commands.py from the Intel media driver (MIT licence) hardware command definitions for Gen9 (KBL).')
    o.append('// Default images are what the media driver\'s constructors set; each field is {dword, low bit, high bit}. Do not edit by hand.')
    for kind, struct, short in COMMANDS:
        header, cpp = src[kind]
        text = struct_text(header, struct)
        fields, enums, size = parse_fields(text)
        img, skipped = ctor_image(cpp, struct, fields, enums, size)
        o.append('')
        o.append('// %s_CMD, %d dwords' % (struct, size))
        o.append('constexpr uint32_t k%sDwords = %d;' % (short, size))
        o.append('constexpr uint32_t k%sDefault[%d] = {%s};' % (short, size, ', '.join('0x%08X' % x for x in img)))
        for n, (dw, lo, hi) in sorted(fields.items(), key=lambda kv: (kv[1][0], kv[1][1])):
            o.append('constexpr EncodeField k%s_%s = {%d, %d, %d};' % (short, n, dw, lo, hi))
        for n, v in enums.items():
            if n.startswith(('SUBOPA_', 'SUBOPB_', 'OPCODE_', 'PIPELINE_', 'COMMAND_TYPE_')): continue
            o.append('constexpr uint32_t k%s_%s = %d;' % (short, n, v))
        if skipped:
            print('%s: not applied: %s' % (struct, '; '.join(skipped)), file=sys.stderr)
    open(out, 'w').write('\n'.join(o) + '\n')

main()
