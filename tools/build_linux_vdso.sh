#!/usr/bin/env bash
# Builds the x86-64 Linux vDSO (src/Process/LinuxVdso/vdso_x86_64.c) and writes it as a byte array to src/Process/LinuxVdso/LinuxVdsoImage.inc, which
# the kernel embeds. Run it after changing the vDSO source, its linker script or vdso_data.h, and commit the .inc with the change.
# Needs clang and GNU ld (or ld.lld). The output is reproducible: no build id, no compiler comment, no paths.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
dir="$here/src/Process/LinuxVdso"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
clang --target=x86_64-linux-gnu -std=c11 -O2 -fPIC -ffreestanding -nostdlib -fno-stack-protector -fno-builtin -fcf-protection=none \
  -fno-jump-tables -fasynchronous-unwind-tables -mno-sse -mno-mmx -mno-red-zone -Wall -Wextra -Werror -c "$dir/vdso_x86_64.c" -o "$work/vdso.o"
clang --target=x86_64-linux-gnu -nostdlib -shared -o "$work/vdso.so" "$work/vdso.o" \
  -Wl,-T,"$dir/vdso_x86_64.lds" -Wl,-soname=linux-vdso.so.1 -Wl,--hash-style=both -Wl,--no-undefined -Wl,--build-id=none \
  -Wl,--eh-frame-hdr -Wl,-z,max-page-size=4096 -Wl,-z,noexecstack -Wl,-Bsymbolic -Wl,-s
# (no dynamic relocations: the image is mapped as it is, nothing relocates it)
if readelf -r "$work/vdso.so" | grep -q "R_X86_64"; then echo "the vDSO has relocations" >&2; exit 1; fi
{
  echo "// Generated by tools/build_linux_vdso.sh from vdso_x86_64.c and vdso_x86_64.lds. Do not edit."
  echo "// $(stat -c %s "$work/vdso.so") bytes, sha256 $(sha256sum "$work/vdso.so" | cut -d' ' -f1)"
  od -An -v -tx1 "$work/vdso.so" | sed -E "s/ ([0-9a-f]{2})/0x\1,/g; s/^/ /"
} > "$dir/LinuxVdsoImage.inc"
echo "wrote $dir/LinuxVdsoImage.inc ($(stat -c %s "$work/vdso.so") bytes)"
if [ -n "${KEEP_VDSO:-}" ]; then cp "$work/vdso.so" "$KEEP_VDSO"; fi
