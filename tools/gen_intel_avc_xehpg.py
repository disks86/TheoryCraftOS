#!/usr/bin/env python3
"""Generates src/Hardware/VideoCodec/Intel/IntelEncodeCommandImagesXeHpgAvc.inc: the VDEnc commands of H.264 encode on Arc Alchemist (Xe_HPM, the discrete Xe-HPG).

Arc's H.264 path in the Intel media driver (MIT licence) is the older CodecHal one (codechal_vdenc_avc_xe_hpm.cpp with the MhwVdboxVdencInterfaceXe_Hpm commands): the picture
level VDEnc commands are tables in mhw_vdbox_vdenc_xe_hpm.h indexed by target usage, picture type, quantiser and workarounds. This reads those tables for the configuration the
encoder here uses (target usage 7, constant QP, I and P pictures with a GOP of one reference, no workaround, no stream-in) and writes the images.

usage: gen_intel_avc_xehpg.py <media-driver-dir> <out.inc>

<media-driver-dir> holds:
  legacy_vdenc_hpm.h [media_driver/agnostic/Xe_M/Xe_HPM/hw/vdbox/mhw_vdbox_vdenc_xe_hpm.h]
  hwcmd_hpm.h        [media_driver/agnostic/Xe_M/Xe_HPM/hw/vdbox/mhw_vdbox_vdenc_hwcmd_xe_hpm.h; the media_softlet copy has the same layout]
"""
import os, re, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_intel_hevc_xelpg import brace_block, struct_text, parse_fields, emit_array

QPS = range(10, 52)
LEVELS = range(0, 53)


def numbers_after(text, name):
    """All integers of the initializer of `static const uint32_t name[..]... = { ... };`."""
    m = re.search(r'static const uint32_t %s\[[^=]*=\s*\{' % re.escape(name), text)
    i = m.end() - 1
    depth, j = 0, i
    while True:
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    body = re.sub(r'//[^\n]*', '', text[i:j + 1])
    return [int(x, 0) for x in re.findall(r'0[xX][0-9a-fA-F]+|\d+', body)]


DUMP = r'''
#include <cstdio>
#include "mhw_vdbox_vdenc_hwcmd_xe_hpm.h"
using namespace mhw::vdbox::vdenc::xe_hpm;
template <class T> void d(const char *n) { T c; const uint32_t *p = (const uint32_t *)&c; printf("%s", n); for (size_t i = 0; i < sizeof(T) / 4; i++) printf(" 0x%x", p[i]); printf("\n"); }
int main() { d<Cmd::VDENC_CMD3_CMD>("CMD3"); d<Cmd::VDENC_AVC_IMG_STATE_CMD>("IMG"); d<Cmd::VDENC_AVC_SLICE_STATE_CMD>("SLICE"); d<Cmd::VDENC_PIPE_MODE_SELECT_CMD>("PMS");
         d<Cmd::VDENC_WEIGHTSOFFSETS_STATE_CMD>("WO"); d<Cmd::VDENC_WALKER_STATE_CMD>("WALK"); d<Cmd::VDENC_PIPE_BUF_ADDR_STATE_CMD>("PBA"); }
'''


def ctor_images(d, tmp):
    os.makedirs(tmp + '/stub', exist_ok=True)
    for n in ('mhw_hwcmd.h', 'mos_utilities.h'):
        open(tmp + '/stub/' + n, 'w').write('''#pragma once
#include <stdint.h>
#include <string.h>
#include <stddef.h>
#ifndef MOS_ZeroMemory
#define MOS_ZeroMemory(p, s) memset(p, 0, s)
#define __CODEGEN_MAX(_a, _b) (((_a) > (_b)) ? (_a) : (_b))
#define __CODEGEN_BITFIELD(l, h) (h) - (l) + 1
#define __CODEGEN_OP_LENGTH_BIAS 2
#define __CODEGEN_OP_LENGTH(x) (uint32_t)((__CODEGEN_MAX(x, __CODEGEN_OP_LENGTH_BIAS)) - __CODEGEN_OP_LENGTH_BIAS)
#endif
''')
    os.makedirs(tmp + '/hdr', exist_ok=True)
    open(tmp + '/hdr/mhw_vdbox_vdenc_hwcmd_xe_hpm.h', 'w').write(open(d + '/hwcmd_hpm.h').read())
    open(tmp + '/dump.cpp', 'w').write(DUMP)
    subprocess.check_call(['g++', '-std=c++17', '-w', '-I' + tmp + '/stub', '-I' + tmp + '/hdr', tmp + '/dump.cpp', '-o', tmp + '/dump'])
    out = {}
    for line in subprocess.check_output([tmp + '/dump'], text=True).split('\n'):
        if line:
            k, *v = line.split()
            out[k] = [int(x, 16) for x in v]
    return out


def main():
    d, out_path = sys.argv[1], sys.argv[2]
    legacy = open(d + '/legacy_vdenc_hpm.h').read()
    header = open(d + '/hwcmd_hpm.h').read()
    cmd3 = numbers_after(legacy, 'tableCmd3')
    img = numbers_after(legacy, 'tableAvcImgState')
    dw8 = numbers_after(legacy, 'tableAvcImgState_DW8')
    assert len(cmd3) == 5 * 52 * 22 and len(img) == 7 * 4 * 3 * 2 * 2 * 2 * 19 and len(dw8) == 53, (len(cmd3), len(img), len(dw8))
    with tempfile.TemporaryDirectory() as tmp:
        ctor = ctor_images(d, tmp)
    assert len(ctor['CMD3']) == 23 and len(ctor['IMG']) == 20 and len(ctor['SLICE']) == 4

    def cmd3_row(type_, qp): return cmd3[(type_ * 52 + qp) * 22:(type_ * 52 + qp) * 22 + 22]
    def img_row(tu_minus1, type_): return img[((((tu_minus1 * 4 + type_) * 3 + 0) * 2 + 0) * 2 + 0) * 2 * 19 + 0:][:19]   # [ir 0][A step 0][wa 0][stream-in 0]

    o = ['// Generated by tools/gen_intel_avc_xehpg.py from the Intel media driver (MIT licence): the VDEnc commands of H.264 encode on Arc Alchemist (Xe_HPM), constant QP, target usage 7,',
         '// one slice, I and P pictures (GOP of one reference). Do not edit by hand.']
    # VDENC_CMD3: AddVdencCmd3Cmd. I pictures use type 0 and (for a single reference list entry) clear bits 8..11 of dword 13; P pictures with GopRefDist 1 use type 2.
    for tn, t in (('I', 0), ('P', 2)):
        words = []
        for qp in QPS:
            row = [ctor['CMD3'][0]] + cmd3_row(t, qp)
            if tn == 'I': row[13] &= 0xf0ff
            words += row
        o += ['', '// VDENC_CMD3, 23 dwords for each quantiser %d .. %d, %s pictures' % (QPS[0], QPS[-1], tn), emit_array('kXeHpgAvcVdencCmd3Table%s' % tn, words)]
    o += ['', 'constexpr uint32_t kXeHpgAvcVdencCmd3Dwords = 23;']
    # VDENC_AVC_IMG_STATE: the table row is dwords 1 .. 19; the driver then sets named fields (the encoder does, with the same field map) and ORs dword 8 by level.
    for tn, t in (('I', 0), ('P', 1)):
        row = [ctor['IMG'][0]] + img_row(6, t)
        row[8] = (row[8] & 0xffff) | 0      # dword 8 = (row & 0xffff) | level table
        o += ['', '// VDENC_AVC_IMG_STATE, 20 dwords, %s pictures at target usage 7 (dword 8 holds only its low half; the level adds the rest from the table below)' % tn, emit_array('kXeHpgAvcVdencImgState%s' % tn, row)]
    o += ['', '// dword 8 high half by level_idc 0 .. 52', emit_array('kXeHpgAvcVdencImgStateLevelDword8', dw8), 'constexpr uint32_t kXeHpgAvcVdencImgStateDwords = 20;']
    # Arc's header keeps the bit fields of most dwords in macros (#define VDENC_AVC_IMG_STATE_CMD_DW<n> union {...}) used inside the command.
    fields = dict(parse_fields(struct_text(header, 'VDENC_AVC_IMG_STATE_CMD', '    ')))
    for m in re.finditer(r'#define VDENC_AVC_IMG_STATE_CMD_DW(\d+)\s*\\\n((?:.*\\\n)*.*)', header):
        for f in re.finditer(r'uint32_t\s+(\w+)\s*:\s*__CODEGEN_BITFIELD\(\s*(\d+),\s*(\d+)\)', m.group(2)):
            if not f.group(1).startswith('Reserved'): fields[f.group(1)] = (int(m.group(1)), int(f.group(2)), int(f.group(3)))
    for n, (dw, lo, hi) in sorted(fields.items(), key=lambda kv: kv[1]):
        o.append('constexpr EncodeField kXeHpgAvcVdencImgState_%s = {%d, %d, %d};' % (n, dw, lo, hi))
    for tag, name, struct, ind in [('SLICE', 'AvcVdencSliceState', 'VDENC_AVC_SLICE_STATE_CMD', '    '), ('WALK', 'AvcVdencWalkerState', 'VDENC_WALKER_STATE_CMD', '    ')]:
        o += ['', '// %s, %d dwords' % (struct, len(ctor[tag])), 'constexpr uint32_t kXeHpg%sDwords = %d;' % (name, len(ctor[tag])), emit_array('kXeHpg%sImage' % name, ctor[tag])]
        for n, (dw, lo, hi) in sorted(parse_fields(struct_text(header, struct, ind)).items(), key=lambda kv: kv[1]):
            o.append('constexpr EncodeField kXeHpg%s_%s = {%d, %d, %d};' % (name, n, dw, lo, hi))
    open(out_path, 'w').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
