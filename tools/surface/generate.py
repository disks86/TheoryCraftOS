#!/usr/bin/env python3
"""Writes src/Browser/DomBindingsSurface.cpp from a dump made with tools/surface/dump.html.

Usage: tools/surface/generate.py dump.json   (run from the repository root)
"""
import json, sys

LICENSE = open('src/Browser/DomBindingsRtc.cpp').read().split('*/', 1)[0] + '*/\n'

def main():
    d = json.load(open(sys.argv[1]))
    assert len(d['win']) == len(d['kinds'])
    for name, names in d['protos'].items():
        assert len(names) == len(d['shapes'][name].split(',')), name
    table = json.dumps({'win': d['win'], 'kinds': d['kinds'], 'lens': d['lens'], 'protos': d['protos'], 'shapes': d['shapes']}, separators=(',', ':'))
    assert ')SURFACE"' not in table
    pieces = [table[i:i + 12000] for i in range(0, len(table), 12000)]
    out = LICENSE + '''
// The interface surface of the reference browser, as data: the property names of the window of a blank frame in the order that browser lists them,
// the kind of each value, the declared argument count of each function, and the property names of each interface's prototype with the shape of
// each member (the letters are explained in tools/surface/dump.html). Generated by tools/surface/generate.py from a dump made with
// tools/surface/dump.html (reference: ''' + d['ua'].replace('\\', '').replace('"', '') + ''') - do not edit by hand.
//
// What it is for: scripts that attest the browser they run in (YouTube's among them) make a blank frame, list the properties of its window and of
// interfaces in it at positions of their choosing, and their server accepts only the lists of browsers it knows. A blank frame that the page around
// it reaches into lists its properties from this table (WebPrelude.cpp: referenceSurface). Nothing else is changed by it: the windows of pages and of
// frames with a document of their own list what this browser really has.
//   __reference_surface() -> the table as JSON text
#include "Browser/DomBindingsInternal.hpp"

namespace browser {
namespace bind {

namespace {

#define NATIVE(name) bool name(Vm& vm, const Value& self, const Value* args, uint32_t argc, Value* result)

const char* const kSurface[] = {
'''
    for p in pieces:
        out += '    R"SURFACE(' + p + ')SURFACE",\n'
    out += '''};

NATIVE(reference_surface) {
  (void)self; (void)args; (void)argc;
  String text(vm.allocator());
  for (const char* piece : kSurface)
    if (!text.append(StringView(piece))) return vm.throw_error(script::ErrorKind::RangeError, "out of memory");
  *result = str_value(vm, text.view());
  return true;
}

}  // namespace

bool install_surface(DomBindings::Impl& c) {
  Vm& vm = c.vm;
  vm.define_native(vm.global(), "__reference_surface", reference_surface, 0);
  return !vm.halted();
}

}  // namespace bind
}  // namespace browser
'''
    open('src/Browser/DomBindingsSurface.cpp', 'w').write(out)
    print('wrote src/Browser/DomBindingsSurface.cpp:', len(d['win']), 'names,', len(d['protos']), 'interfaces,', len(table), 'bytes of table')

main()
