#!/usr/bin/env python3
"""Generates src/Hardware/GraphicsProcessingUnit/AMD/Gcn/GcnRegisters.inc: the register offsets, field shifts and masks, enumerations and PM4 opcodes the draw state
(GcnState) and the command processor model (GcnCp) use, taken from the Linux kernel's headers (v6.12):

  drivers/gpu/drm/amd/include/asic_reg/gca/gfx_8_0_d.h, gfx_8_0_sh_mask.h, gfx_8_0_enum.h and drivers/gpu/drm/amd/amdgpu/vid.h

usage: gen_gcn_registers.py <directory holding the four files> > GcnRegisters.inc
"""
import re, sys, os

REGS = """SPI_SHADER_PGM_LO_PS SPI_SHADER_PGM_HI_PS SPI_SHADER_PGM_RSRC1_PS SPI_SHADER_PGM_RSRC2_PS SPI_SHADER_USER_DATA_PS_0
SPI_SHADER_PGM_LO_VS SPI_SHADER_PGM_HI_VS SPI_SHADER_PGM_RSRC1_VS SPI_SHADER_PGM_RSRC2_VS SPI_SHADER_USER_DATA_VS_0
SPI_SHADER_POS_FORMAT SPI_SHADER_Z_FORMAT SPI_SHADER_COL_FORMAT SPI_PS_INPUT_ENA SPI_PS_INPUT_ADDR SPI_PS_IN_CONTROL SPI_PS_INPUT_CNTL_0 SPI_VS_OUT_CONFIG SPI_BARYC_CNTL
VGT_SHADER_STAGES_EN VGT_PRIMITIVE_TYPE VGT_NUM_INSTANCES VGT_DRAW_INITIATOR VGT_INDEX_TYPE VGT_MAX_VTX_INDX VGT_MIN_VTX_INDX VGT_OUTPUT_PATH_CNTL
CB_COLOR0_BASE CB_COLOR0_PITCH CB_COLOR0_SLICE CB_COLOR0_VIEW CB_COLOR0_INFO CB_COLOR0_ATTRIB CB_TARGET_MASK CB_SHADER_MASK CB_COLOR_CONTROL CB_BLEND0_CONTROL
DB_DEPTH_CONTROL DB_RENDER_CONTROL DB_SHADER_CONTROL DB_COUNT_CONTROL DB_DEPTH_INFO DB_Z_INFO DB_STENCIL_INFO DB_RENDER_OVERRIDE
PA_CL_VPORT_XSCALE PA_CL_VPORT_XOFFSET PA_CL_VPORT_YSCALE PA_CL_VPORT_YOFFSET PA_CL_VPORT_ZSCALE PA_CL_VPORT_ZOFFSET PA_CL_VTE_CNTL PA_CL_CLIP_CNTL PA_CL_VS_OUT_CNTL
PA_SU_SC_MODE_CNTL PA_SU_VTX_CNTL PA_SC_MODE_CNTL_0 PA_SC_MODE_CNTL_1 PA_SC_SCREEN_SCISSOR_TL PA_SC_SCREEN_SCISSOR_BR PA_SC_WINDOW_SCISSOR_TL PA_SC_WINDOW_SCISSOR_BR
PA_SC_GENERIC_SCISSOR_TL PA_SC_GENERIC_SCISSOR_BR PA_SC_VPORT_SCISSOR_0_TL PA_SC_VPORT_SCISSOR_0_BR PA_SC_VPORT_ZMIN_0 PA_SC_VPORT_ZMAX_0 PA_SC_WINDOW_OFFSET PA_SC_CLIPRECT_RULE
PA_CL_GB_VERT_CLIP_ADJ PA_CL_GB_VERT_DISC_ADJ PA_CL_GB_HORZ_CLIP_ADJ PA_CL_GB_HORZ_DISC_ADJ""".split()

ENUMS = """SPI_SHADER_4COMP SPI_SHADER_32_ABGR SPI_SHADER_ZERO DI_PT_TRILIST DI_SRC_SEL_DMA DI_SRC_SEL_AUTO_INDEX DI_INDEX_SIZE_16_BIT DI_INDEX_SIZE_32_BIT
COLOR_32_32_32_32 NUMBER_FLOAT SWAP_STD ENDIAN_NONE ARRAY_LINEAR_GENERAL CB_NORMAL
CS_PARTIAL_FLUSH PS_PARTIAL_FLUSH CACHE_FLUSH_AND_INV_TS_EVENT BOTTOM_OF_PIPE_TS""".split()

COHER = "TCL1_ACTION_ENA TC_ACTION_ENA TC_WB_ACTION_ENA CB_ACTION_ENA DB_ACTION_ENA SH_KCACHE_ACTION_ENA SH_ICACHE_ACTION_ENA".split()

PACKETS = """NOP CONTEXT_CONTROL INDEX_TYPE NUM_INSTANCES DRAW_INDEX_2 DRAW_INDEX_AUTO WRITE_DATA SURFACE_SYNC EVENT_WRITE EVENT_WRITE_EOP SET_CONTEXT_REG SET_SH_REG SET_UCONFIG_REG
INDEX_BASE ACQUIRE_MEM""".split()

def main():
    d = sys.argv[1]
    regs = open(os.path.join(d, 'gfx_8_0_d.h')).read()
    mask = open(os.path.join(d, 'gfx_8_0_sh_mask.h')).read()
    enum = open(os.path.join(d, 'gfx_8_0_enum.h')).read()
    vid = open(os.path.join(d, 'vid.h')).read()
    out = ["// Generated by scripts/gen_gcn_registers.py from the Linux kernel's gfx_8_0_d.h, gfx_8_0_sh_mask.h, gfx_8_0_enum.h and vid.h (v6.12). Do not edit.", ""]
    out.append("// Register offsets (dwords: the SH registers from 0x2C00, the context registers from 0xA000, the uconfig registers from 0xC000)")
    for r in REGS:
        m = re.search(r'^#define\s+mm%s\s+(0x[0-9a-fA-F]+)' % r, regs, re.M)
        if not m: sys.exit("no register " + r)
        out.append("constexpr uint32_t mm%s = %s;" % (r, m.group(1)))
    out.append("")
    out.append("// Fields")
    for r in REGS:
        for m in re.finditer(r'^#define\s+(%s__\w+?(?:__SHIFT|_MASK))\s+(0x[0-9a-fA-F]+)L?' % r, mask, re.M):
            out.append("constexpr uint32_t %s = %s;" % (m.group(1), m.group(2).rstrip('L')))
    out.append("")
    out.append("// Enumerations")
    for e in ENUMS:
        m = re.search(r'^\s*%s\s*=\s*(0x[0-9a-fA-F]+|\d+)' % e, enum, re.M)
        if not m: sys.exit("no enum " + e)
        out.append("constexpr uint32_t k%s = %s;" % (e, m.group(1)))
    out.append("")
    out.append("// PM4 opcodes")
    for p in PACKETS:
        m = re.search(r'^#define\s+PACKET3_%s\s+(0x[0-9a-fA-F]+)' % p, vid, re.M)
        if not m: sys.exit("no packet " + p)
        out.append("constexpr uint32_t kPacket3%s = %s;" % (''.join(w.capitalize() for w in p.split('_')), m.group(1)))
    out.append("")
    out.append("// ACQUIRE_MEM / SURFACE_SYNC cache actions (vid.h)")
    for c in COHER:
        m = re.search(r'#\s*define\s+PACKET3_%s\s+\(1 << (\d+)\)' % c, vid)
        if not m: sys.exit("no coher bit " + c)
        out.append("constexpr uint32_t kCoher%s = 1u << %s;" % (''.join(w.capitalize() for w in c.split('_')), m.group(1)))
    print("\n".join(out))

main()
