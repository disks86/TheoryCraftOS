"""Regenerates the two lists of vulkan-1.dll from its source:
  src/Windows/vulkan-1/vk_exports.inc   X(name) for every function the driver defines (vkGetInstanceProcAddr's table)
  src/Windows/stubs/vulkan-1.inc        X(name) for the Vulkan 1.0 - 1.3 core and the WSI functions of the surfaces and swapchains that a real vulkan-1.dll exports and the driver does not
                                        define yet (they are linked in as functions that answer VK_ERROR_FEATURE_NOT_PRESENT)
Run it after adding or removing a function: scripts/gen-vulkan-exports.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / "src/Windows/vulkan-1"
defined = set()
for f in sorted(src.glob("*.inc")) + [src / "vulkan-1.c"]:
    if f.name in ("vk_exports.inc", "spirv.inc") or f.name.startswith("spirv_"):
        continue
    for m in re.finditer(r"^VKAPI\s+[\w\s\*]+?VKAPI_CALL\s+(vk\w+)\(", f.read_text(), re.M):
        defined.add(m.group(1))
(src / "vk_exports.inc").write_text("/* Generated by scripts/gen-vulkan-exports.py: the functions vulkan-1.dll defines. */\n" + "".join(f"X({n})\n" for n in sorted(defined)))
header = (src / "khronos/vulkan/vulkan_core.h").read_text()
core = set()
for m in re.finditer(r"#ifndef VK_NO_PROTOTYPES\s*\n(.*?)#endif", header, re.S):
    for f in re.finditer(r"VKAPI_CALL\s+(vk\w+)\(", m.group(1)):
        core.add(f.group(1))
# only the versions 1.0 .. 1.3 and the functions of the extensions a program links to directly (surface, swapchain) are exported by a real loader
wanted = set()
for m in re.finditer(r"#define (VK_VERSION_1_[0-3]) 1\s*\n(.*?)(?=#define VK_VERSION_|#define VK_KHR_surface |\Z)", header, re.S):
    for f in re.finditer(r"VKAPI_CALL\s+(vk\w+)\(", m.group(2)):
        wanted.add(f.group(1))
for m in re.finditer(r"#define (VK_KHR_(?:surface|swapchain|win32_surface)) 1\s*\n(.*?)(?=#define VK_\w+ 1\n|\Z)", header, re.S):
    for f in re.finditer(r"VKAPI_CALL\s+(vk\w+)\(", m.group(2)):
        wanted.add(f.group(1))
wsi = (src / "khronos/vulkan/vulkan_win32.h").read_text()
for f in re.finditer(r"VKAPI_CALL\s+(vk\w+KHR)\(", wsi):
    if "Win32Surface" in f.group(1) or "Win32Presentation" in f.group(1):
        wanted.add(f.group(1))
missing = sorted(wanted - defined)
dw = (root / "src/Windows/stubs/dwmapi.inc").read_text()
stub_header = dw[:dw.index("*/") + 3]
(root / "src/Windows/stubs/vulkan-1.inc").write_text(stub_header + """/* The exports of vulkan-1.dll that are not implemented yet: generated by scripts/gen-vulkan-exports.py.
 * To implement one, define it in the DLL and run the script again. */
""" + "".join(f"X({n})\n" for n in missing))
print(len(defined), "defined,", len(missing), "stubs")
