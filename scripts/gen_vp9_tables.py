#!/usr/bin/env python3
"""Extracts the normative constant tables of VP9 and the integer transform kernels from a libvpx source tree (BSD-3-Clause, Copyright
The WebM Project Authors) into src/Hardware/VideoCodec/Software/Vp9Tables.inc and Vp9Transform.inc.

Usage: scripts/gen_vp9_tables.py <libvpx-checkout> [output-directory]
The tables keep libvpx's declarations (names, dimensions, enumerator names): Vp9Tables.hpp defines the enumerators and structs they use.
"""
import re, sys, os

root = sys.argv[1]
out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'src', 'Hardware', 'VideoCodec', 'Software')

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

cache = {}
def source(path):
    if path not in cache:
        cache[path] = strip_comments(open(os.path.join(root, path)).read())
    return cache[path]

def balanced(text, start):
    """text[start] == '{': returns the index just after the matching '}'."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '{': depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0: return i + 1
    raise SystemExit('unbalanced braces')

def table(path, name, ctype, dims=None):
    text = source(path)
    m = re.search(r'\b' + re.escape(name) + r'\s*((?:\[[^\]]*\]\s*)*)\)?\s*=\s*\{', text)
    if not m:
        raise SystemExit('table %s not found in %s' % (name, path))
    body_start = m.end() - 1
    body = text[body_start:balanced(text, body_start)]
    body = re.sub(r'\s+', ' ', body)
    d = dims if dims is not None else re.sub(r'\s+', '', m.group(1))
    return 'static const %s %s%s = %s;' % (ctype, name, d, body)

U8, I8, I16, I32, U16 = 'uint8_t', 'int8_t', 'int16_t', 'int32_t', 'uint16_t'
lines = ['// Generated by scripts/gen_vp9_tables.py from libvpx (BSD-3-Clause, Copyright (c) The WebM Project authors). Do not edit.', '']
add = lambda *a, **k: lines.append(table(*a, **k))

C = 'vp9/common/vp9_common_data.c'
for n in ['b_width_log2_lookup', 'b_height_log2_lookup', 'num_4x4_blocks_wide_lookup', 'num_4x4_blocks_high_lookup', 'mi_width_log2_lookup',
          'num_8x8_blocks_wide_lookup', 'num_8x8_blocks_high_lookup', 'size_group_lookup', 'subsize_lookup', 'max_txsize_lookup', 'txsize_to_bsize',
          'tx_mode_to_biggest_tx_size', 'ss_size_lookup', 'uv_txsize_lookup']:
    add(C, n, U8)
add(C, 'partition_context_lookup', 'PartitionContext')
E = 'vp9/common/vp9_entropy.c'
for n in ['vp9_cat1_prob', 'vp9_cat2_prob', 'vp9_cat3_prob', 'vp9_cat4_prob', 'vp9_cat5_prob', 'vp9_cat6_prob', 'vp9_cat6_prob_high12']:
    add(E, n, U8)
add(E, 'vp9_coefband_trans_8x8plus', U8)
add(E, 'vp9_coefband_trans_4x4', U8)
add(E, 'vp9_pt_energy_class', U8)
add(E, 'vp9_pareto8_full', U8, '[255][8]')
for s in ['4x4', '8x8', '16x16', '32x32']:
    add(E, 'default_coef_probs_' + s, U8, '[2][2][6][6][3]')
M = 'vp9/common/vp9_entropymode.c'
add(M, 'vp9_kf_y_mode_prob', U8)
add(M, 'vp9_kf_uv_mode_prob', U8)
add(M, 'default_if_y_probs', U8)
add(M, 'default_if_uv_probs', U8)
add(M, 'vp9_kf_partition_probs', U8)
add(M, 'default_partition_probs', U8)
add(M, 'default_inter_mode_probs', U8)
add(M, 'default_intra_inter_p', U8)
add(M, 'default_comp_inter_p', U8)
add(M, 'default_comp_ref_p', U8)
add(M, 'default_single_ref_p', U8)
add(M, 'default_skip_probs', U8)
add(M, 'default_switchable_interp_prob', U8, '[4][2]')
add(M, 'vp9_intra_mode_tree', I8)
add(M, 'vp9_inter_mode_tree', I8)
add(M, 'vp9_partition_tree', I8)
add(M, 'vp9_switchable_interp_tree', I8, '[4]')
# default_tx_probs is a struct in libvpx; written here as the three arrays it holds
tx = source(M)
m = re.search(r'default_tx_probs\s*=\s*\{', tx)
body = tx[m.end() - 1:balanced(tx, m.end() - 1)]
lines.append('static const TxProbs default_tx_probs = %s;' % re.sub(r'\s+', ' ', body))
V = 'vp9/common/vp9_entropymv.c'
add(V, 'vp9_mv_joint_tree', I8)
add(V, 'vp9_mv_class_tree', I8)
add(V, 'vp9_mv_class0_tree', I8)
add(V, 'vp9_mv_fp_tree', I8)
add(V, 'log_in_base_2', U8)
lines.append('static const NmvContext default_nmv_context = %s;' % re.sub(r'\s+', ' ', (lambda t: (lambda m: t[m.end() - 1:balanced(t, m.end() - 1)])(re.search(r'default_nmv_context\s*=\s*\{', t)))(source(V))))
S = 'vp9/common/vp9_scan.c'
st = source(S)
for m in re.finditer(r'\b((?:default|col|row)_scan_\d+x\d+(?:_neighbors)?)\s*(\[[^\]]*\])', st):
    add(S, m.group(1), I16)
Q = 'vp9/common/vp9_quant_common.c'
for n in ['dc_qlookup', 'dc_qlookup_10', 'dc_qlookup_12', 'ac_qlookup', 'ac_qlookup_10', 'ac_qlookup_12']:
    add(Q, n, I16)
F = 'vp9/common/vp9_filter.c'
for n in ['bilinear_filters', 'sub_pel_filters_8', 'sub_pel_filters_8lp', 'sub_pel_filters_8s']:
    add(F, n, I16, '[16][8]')
R = 'vp9/common/vp9_mvref_common.h'
add(R, 'mode_2_counter', U8)
add(R, 'counter_to_context', U8)
add(R, 'mv_ref_blocks', 'Position')
add(R, 'idx_n_column_to_subblock', U8)
G = 'vp9/common/vp9_seg_common.c'
add(G, 'seg_feature_data_max', I32)
add(G, 'vp9_segment_tree', I8)
P = 'vpx_dsp/prob.h'
add(P, 'count_to_update_factor', U8)
add('vpx_dsp/prob.c', 'vpx_norm', U8)
add('vp9/decoder/vp9_dsubexp.c', 'inv_map_table', U8)
add('vp9/common/vp9_loopfilter.c', 'mode_lf_lut', U8)
add('vp9/common/vp9_reconintra.c', 'intra_mode_to_tx_type_lookup', U8)
open(os.path.join(out_dir, 'Vp9Tables.inc'), 'w').write('\n'.join(lines) + '\n')

# transform kernels, verbatim except for the types
T = 'vpx_dsp/inv_txfm.c'
tt = strip_comments(open(os.path.join(root, T)).read())
def function(name):
    m = re.search(r'\b(?:static\s+)?void\s+' + re.escape(name) + r'\s*\([^)]*\)\s*\{', tt)
    if not m: raise SystemExit('function %s' % name)
    end = balanced(tt, m.end() - 1)
    return tt[m.start():end]
out = ['// Generated by scripts/gen_vp9_tables.py from libvpx vpx_dsp/inv_txfm.c (BSD-3-Clause, Copyright (c) The WebM Project authors). Do not edit.', '']
for n in ['vpx_highbd_iadst4_c', 'vpx_highbd_idct4_c', 'vpx_highbd_iadst8_c', 'vpx_highbd_idct8_c', 'vpx_highbd_iadst16_c', 'vpx_highbd_idct16_c', 'highbd_idct32_c']:
    out.append(function(n))
    out.append('')
open(os.path.join(out_dir, 'Vp9Transform.inc'), 'w').write('\n'.join(out) + '\n')
print('ok')
