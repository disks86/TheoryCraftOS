#!/usr/bin/env python3
"""Extracts the large normative constant tables of VP8 from a libvpx source tree (BSD-3-Clause, Copyright The WebM Project Authors)
into src/Hardware/VideoCodec/Software/Vp8Tables.inc.

Usage: scripts/gen_vp8_tables.py <libvpx-checkout> [output-directory]
The tables keep libvpx's names and dimensions; the small ones (trees, mode contexts, filters) are written out in Vp8.cpp.
"""
import re, sys, os

root = sys.argv[1]
out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'src', 'Hardware', 'VideoCodec', 'Software')

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

def table(path, name, ctype, dims):
    text = strip_comments(open(os.path.join(root, path)).read())
    m = re.search(r'\b' + re.escape(name) + r'\s*(?:\[[^\]]*\]\s*)*\)?\s*=\s*\{', text)
    if not m:
        raise SystemExit('table %s not found in %s' % (name, path))
    start = m.end() - 1
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '{': depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    body = re.sub(r'\s+', ' ', text[start:end])
    return 'static const %s %s%s = %s;' % (ctype, name, dims, body)

lines = ['// Generated by scripts/gen_vp8_tables.py from libvpx (BSD-3-Clause, Copyright (c) The WebM Project authors). Do not edit.', '']
lines.append(table('vp8/common/default_coef_probs.h', 'default_coef_probs', 'uint8_t', '[4][8][3][11]'))
lines.append(table('vp8/common/coefupdateprobs.h', 'vp8_coef_update_probs', 'uint8_t', '[4][8][3][11]'))
lines.append(table('vp8/common/vp8_entropymodedata.h', 'vp8_kf_bmode_prob', 'uint8_t', '[10][10][9]'))
lines.append(table('vp8/common/quant_common.c', 'dc_qlookup', 'int16_t', '[128]'))
lines.append(table('vp8/common/quant_common.c', 'ac_qlookup', 'int16_t', '[128]'))
open(os.path.join(out_dir, 'Vp8Tables.inc'), 'w').write('\n'.join(lines) + '\n')
