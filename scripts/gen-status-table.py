"""Writes src/Windows/ntdll/status.inc: the NTSTATUS -> Win32 error table of RtlNtStatusToDosError. The pairs are the mappings that Windows documents and that
tests/windows/wine/ntdll/error.c checks (the first error listed is the one Windows returns)."""
import os
import re
import subprocess

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
inc = os.path.join(root, "tests", "windows", "wine", "include")
text = open(os.path.join(root, "tests", "windows", "wine", "ntdll", "error.c")).read()
pairs = []
for m in re.finditer(r"^\s*cmp[234]?\(\s*(STATUS_\w+)\s*,\s*(\w+)", text, re.M):
    pairs.append((m.group(1), m.group(2)))
values = {}
for header in ("ntstatus.h", "winerror.h"):
    for m in re.finditer(r"^#define\s+(\w+)\s+\(?(?:\(\w+\)\s*)?(0x[0-9A-Fa-f]+|\d+)\)?[Ll]?\s*(?:/\*.*)?$", open(os.path.join(inc, header), errors="replace").read(), re.M):
        values.setdefault(m.group(1), int(m.group(2), 0))
table = {}
for status, error in pairs:
    if status in values and error in values:
        table.setdefault(values[status] & 0xFFFFFFFF, values[error])
with open(os.path.join(root, "src", "Windows", "ntdll", "status.inc"), "w") as f:
    f.write("/* NTSTATUS -> Win32 error, sorted by status: generated by scripts/gen-status-table.py. */\nstatic const struct { ULONG status, error; } status_table[] = {\n")
    for s in sorted(table):
        f.write("  {0x%08Xu, %d},\n" % (s, table[s]))
    f.write("};\n")
print(len(table), "of", len(pairs), "pairs")
