#!/usr/bin/env python3
"""Generates AmdVcnAv1Context.inc: the initial entropy (CDF) contexts the VCN AV1 decoder expects at the start of its context buffer, four of them one per
quantizer category, in the firmware's own layout. The tables and the code that fills them are Mesa's (radeon_vcn_av1_default.h and the init functions of
radeon_vcn_dec.c, Copyright Advanced Micro Devices, Inc.; MIT license): they are compiled together with a few lines of main() and the program's output is stored as
runs of non-zero bytes.

  gen_vcn_av1_context.py out.inc radeon_vcn_av1_default.h radeon_vcn_dec.c

The two inputs are untrusted: they are only compiled (never run on their own), in a temporary directory.
"""
import os
import subprocess
import sys
import tempfile

MAIN = r'''
static unsigned align(unsigned v, unsigned a) { return (v + a - 1) / a * a; }
int main(int argc, char **argv) {
  unsigned stride = align(sizeof(rvcn_av1_frame_context_t), 2048);
  printf("%zu %u %zu\n", sizeof(rvcn_av1_frame_context_t), stride, sizeof(rvcn_av1_hw_frame_context_t));
  unsigned char *p = calloc(4, stride);
  for (int i = 0; i < 4; ++i) {
    rvcn_init_mode_probs(p + (size_t)i * stride);
    rvcn_av1_init_mv_probs(p + (size_t)i * stride);
    rvcn_av1_default_coef_probs(p + (size_t)i * stride, i);
  }
  FILE *f = fopen(argv[1], "wb");
  fwrite(p, 4, stride, f);
  fclose(f);
  return 0;
}
'''


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    out_path, defaults, source = sys.argv[1:]
    text = open(source).read()
    a = text.index('static void rvcn_init_mode_probs')
    b = text.index('static void rvcn_av1_default_coef_probs')
    e = text.index('\n}\n', b) + 3
    program = '#include <stdint.h>\n#include <stdio.h>\n#include <string.h>\n#include <stdlib.h>\n' + open(defaults).read() + '\n' + text[a:e] + MAIN
    with tempfile.TemporaryDirectory() as tmp:
        src, exe, blob = (os.path.join(tmp, n) for n in ('ctx.c', 'ctx', 'blob.bin'))
        open(src, 'w').write(program)
        subprocess.check_call(['gcc', '-std=gnu11', '-w', '-o', exe, src])
        sizes = subprocess.check_output([exe, blob], text=True).split()
        data = open(blob, 'rb').read()
    frame_context, stride, hw_context = (int(v) for v in sizes)
    assert len(data) == 4 * stride
    # Runs of non-zero bytes; zero gaps shorter than 16 bytes stay inside a run.
    runs, i = [], 0
    while i < len(data):
        if data[i] == 0:
            i += 1
            continue
        j, last = i, i
        while j < len(data) and j - last < 16:
            if data[j]:
                last = j
            j += 1
        runs.append((i, last + 1 - i))
        i = last + 1
    packed = b''.join(data[o:o + n] for o, n in runs)
    lines = ['// Generated by scripts/gen_vcn_av1_context.py from Mesa\'s radeon_vcn_av1_default.h and radeon_vcn_dec.c (Copyright Advanced Micro Devices, Inc.; MIT license).',
             '// The four initial AV1 contexts of the VCN decoder as runs of non-zero bytes; everything between the runs is zero. Do not edit by hand.',
             'constexpr uint32_t kAv1FrameContextBytes = %d;' % frame_context,
             'constexpr uint32_t kAv1ContextStride = %d;      // between two contexts: sizeof(frame context) rounded up to 2048' % stride,
             'constexpr uint32_t kAv1HwFrameContextBytes = %d;' % hw_context,
             'constexpr uint32_t kAv1ContextRunCount = %d;' % len(runs),
             'constexpr uint32_t kAv1ContextRuns[%d][2] = {  // offset in the four contexts, length' % len(runs)]
    row = []
    for o, n in runs:
        row.append('{%d, %d}' % (o, n))
        if len(row) == 8:
            lines.append('    ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ', '.join(row) + ',')
    lines.append('};')
    lines.append('constexpr uint8_t kAv1ContextData[%d] = {' % len(packed))
    for k in range(0, len(packed), 24):
        lines.append('    ' + ', '.join('0x%02X' % v for v in packed[k:k + 24]) + ',')
    lines.append('};')
    open(out_path, 'w').write('\n'.join(lines) + '\n')


main()
