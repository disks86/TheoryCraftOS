#!/usr/bin/env python3
"""Generates Mpeg2Tables.inc: the variable length code tables of ISO/IEC 13818-2 Annex B (macroblock address increment, coded block pattern, motion code,
DC size, and the two DCT coefficient tables B.14 and B.15 with their run and level), the scan tables and the non-linear quantiser scale, as plain arrays.

The numbers are the standard's; they are read from the tables of two decoders (FFmpeg's libavcodec/mpeg12data.c, mpegvideodata.c and mpeg12.c) that agree with each
other and with the stream tests of this OS, and written out here in this OS's own layout. The macroblock type codes, the dmvector codes and the default
quantiser matrices are short enough to be in the template below.

  gen_mpeg2_tables.py out.inc mpeg12data.c mpegvideodata.c

The inputs are untrusted: they are only read as text.
"""
import re
import sys


ZIGZAG = [0, 1, 8, 16, 9, 2, 3, 10, 17, 24, 32, 25, 18, 11, 4, 5, 12, 19, 26, 33, 40, 48, 41, 34, 27, 20, 13, 6, 7, 14, 21, 28,
          35, 42, 49, 56, 57, 50, 43, 36, 29, 22, 15, 23, 30, 37, 44, 51, 58, 59, 52, 45, 38, 31, 39, 46, 53, 60, 61, 54, 47, 55, 62, 63]
DEFAULT_INTRA = [8, 16, 19, 22, 26, 27, 29, 34, 16, 16, 22, 24, 27, 29, 34, 37, 19, 22, 26, 27, 29, 34, 34, 38, 22, 22, 26, 27, 29, 34, 37, 40,
                 22, 26, 27, 29, 32, 35, 40, 48, 26, 27, 29, 32, 35, 40, 48, 58, 26, 27, 29, 34, 38, 46, 56, 69, 27, 29, 35, 38, 46, 56, 69, 83]


def block(text, name):
    m = re.search(re.escape(name) + r'[^=]*=\s*\{(.*?)\n\};', text, re.S)
    if not m:
        sys.exit('table not found: ' + name)
    return m.group(1)


def pairs(text, name):
    body = block(text, name)
    out = []
    for a, b in re.findall(r'\{\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(\d+)\s*\}', body):
        out.append((int(a, 0), int(b)))
    return out


def numbers(text, name):
    body = re.sub(r'/\*.*?\*/', '', block(text, name), flags=re.S)
    return [int(v, 0) for v in re.findall(r'-?(?:0x[0-9a-fA-F]+|\d+)', body)]


def array(name, ctype, values, per_line=12):
    lines = ['constexpr %s %s[%d] = {' % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + per_line]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def codes(name, table):
    """A table of (code, length) as two arrays."""
    return array(name + 'Code', 'uint16_t', [c for c, _ in table]) + '\n' + array(name + 'Bits', 'uint8_t', [b for _, b in table])


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    data = open(sys.argv[2]).read()
    scans = open(sys.argv[3]).read()
    out = ['// Generated by scripts/gen_mpeg2_tables.py from the tables of ISO/IEC 13818-2 Annex B. Do not edit by hand.', '']
    incr = pairs(data, 'ff_mpeg12_mbAddrIncrTable')
    assert len(incr) == 36
    out.append('// B.1 macroblock_address_increment: increments 1 to 33, then the escape (33 is added for each one).')
    out.append(codes('kAddressIncrement', incr[:33]))
    out.append('constexpr uint16_t kAddressEscapeCode = %d;\nconstexpr uint8_t kAddressEscapeBits = %d;' % incr[33])
    pat = pairs(data, 'ff_mpeg12_mbPatTable')
    assert len(pat) == 64
    out.append('// B.9 coded_block_pattern, indexed by the pattern.')
    out.append(codes('kCodedBlockPattern', pat))
    mv = pairs(data, 'ff_mpeg12_mbMotionVectorTable')
    assert len(mv) == 17
    out.append('// B.10 motion_code, indexed by the magnitude (the sign follows for a magnitude that is not 0).')
    out.append(codes('kMotionCode', mv))
    dcl = list(zip(numbers(data, 'ff_mpeg12_vlc_dc_lum_code'), numbers(data, 'ff_mpeg12_vlc_dc_lum_bits')))
    dcc = list(zip(numbers(data, 'ff_mpeg12_vlc_dc_chroma_code'), numbers(data, 'ff_mpeg12_vlc_dc_chroma_bits')))
    assert len(dcl) == 12 and len(dcc) == 12
    out.append('// B.12 and B.13 dct_dc_size_luminance and dct_dc_size_chrominance, indexed by the size.')
    out.append(codes('kDcSizeLuma', dcl))
    out.append(codes('kDcSizeChroma', dcc))
    run = numbers(data, 'ff_mpeg12_run')
    level = numbers(data, 'ff_mpeg12_level')
    assert len(run) == len(level) == 111
    out.append('// B.14 and B.15 DCT coefficients: the (run, level) of each of the 111 codes, then each table\'s codes; index 111 is the escape, 112 the end of block.')
    out.append(array('kDctRun', 'uint8_t', run))
    out.append(array('kDctLevel', 'uint8_t', level))
    b14 = pairs(data, 'ff_mpeg1_vlc_table')
    b15 = pairs(data, 'ff_mpeg2_vlc_table')
    assert len(b14) == len(b15) == 113
    out.append(codes('kDctTable0', b14))
    out.append(codes('kDctTable1', b15))
    out.append('// 7.3 the scans, as the position (row * 8 + column) of each coefficient in coding order: the zigzag scan and the alternate scan.')
    out.append(array('kZigzagScan', 'uint8_t', ZIGZAG, 16))
    out.append(array('kAlternateScan', 'uint8_t', numbers(scans, 'ff_alternate_vertical_scan')[:64], 16))
    out.append('// 6.3.11 the intra quantiser matrix that applies when none is sent, by position (the non-intra one is flat 16).')
    out.append(array('kDefaultIntraMatrix', 'uint8_t', DEFAULT_INTRA, 8))
    out.append('// 7.4.2.2 the quantiser scale of quantiser_scale_code when q_scale_type is 1.')
    out.append(array('kNonLinearScale', 'uint8_t', numbers(scans, 'ff_mpeg2_non_linear_qscale')[:32], 16))
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


main()
