#!/usr/bin/env python3
"""Turns an MPEG-4 Part 2 elementary stream and FFmpeg's decode of it into the self-test include AmdVcnSelfTestMpeg4Stream.inc: the stream as a C++ array, cut into one packet
per video object plane (the headers in front of a plane go with it), where each packet ends, and the decoded pictures in display order (planar 8-bit 4:2:0, the reference
the engine's pictures are held to).

  gen_mpeg4_selftest_inc.py stream.m4v decoded.yuv out.inc

The inputs are only read, never executed.
"""
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    d = open(sys.argv[1], 'rb').read()
    yuv = open(sys.argv[2], 'rb').read()
    # A packet ends before the first start code that follows a plane's data.
    codes, i = [], d.find(b'\x00\x00\x01')
    while 0 <= i < len(d) - 3:
        codes.append((i, d[i + 3]))
        i = d.find(b'\x00\x00\x01', i + 3)
    cuts, seen_plane = [], False
    for pos, code in codes:
        if seen_plane:
            cuts.append(pos)
            seen_plane = False
        if code == 0xB6:
            seen_plane = True
    ends = cuts + [len(d)]
    size = 32
    frame = size * size * 3 // 2
    if len(yuv) != frame * len(ends):
        sys.exit('decoded.yuv holds %d bytes, expected %d pictures of %d' % (len(yuv), len(ends), frame))

    def rows(data, per):
        return '\n'.join('    ' + ', '.join('0x%02X' % b for b in data[j:j + per]) + ',' for j in range(0, len(data), per))

    out = ('// Generated by scripts/gen_mpeg4_selftest_inc.py (see scripts/gen_mpeg4_selftest.sh): a %d x %d stream of %d pictures (one packet each, in coding order, with B planes)\n'
           '// and FFmpeg\'s decode of it, the stream the UVD 6 MPEG-4 self-test has the engine decode. Do not edit by hand.\n'
           'constexpr uint32_t kMpeg4SelfTestPictures = %d;\n'
           'constexpr uint32_t kMpeg4SelfTestSize = %d;\n'
           'constexpr uint64_t kMpeg4SelfTestEnds[%d] = {%s};\n'
           'constexpr uint8_t kMpeg4SelfTestStream[%d] = {\n%s\n};\n'
           '// The pictures in display order, planar I420.\n'
           'constexpr uint8_t kMpeg4SelfTestExpected[%d] = {\n%s\n};\n') % (
               size, size, len(ends), len(ends), size, len(ends), ', '.join(str(e) for e in ends), len(d), rows(d, 24), len(yuv), rows(yuv, 24))
    open(sys.argv[3], 'w').write(out)


main()
