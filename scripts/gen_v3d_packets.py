#!/usr/bin/env python3
"""Generates V3dPackets.inc, the bit layout of the V3D 4.2 control list packets and records the OS uses, from Mesa's
src/broadcom/cle/v3d_packet.xml (MIT licensed; the layout is a hardware fact, this script only transcribes it).

Usage: scripts/gen_v3d_packets.py path/to/v3d_packet.xml > src/Hardware/GraphicsProcessingUnit/Broadcom/V3dPackets.inc

Field positions follow Mesa's gen_pack_header.py: a packet is its opcode byte followed by its fields, whose <field start> counts from the bit after the opcode
(shifted up by 8 here); a record (struct) has no opcode and its starts are as written ("24b" is byte 24).
"""
import re
import sys
import xml.etree.ElementTree as ET

VERSION = 42
PACKETS = [
    "Halt", "NOP", "Flush", "Start Tile Binning", "End of rendering", "Flush VCD cache", "Start Address of Generic Tile List",
    "Branch to Implicit Tile List", "Return from sub-list", "Supertile Coordinates", "Clear Tile Buffers", "End of Loads", "End of Tile Marker",
    "Store Tile Buffer General", "Load Tile Buffer General", "Indexed Prim List", "Vertex Array Prims", "Base Vertex Base Instance", "Index Buffer Setup",
    "Set InstanceID", "Prim List Format", "GL Shader State", "VCM Cache Size", "Blend Enables", "Blend Cfg", "Transform Feedback Specs", "Color Write Masks", "Zero All Centroid Flags",
    "Sample State", "Occlusion Query Counter", "Cfg Bits", "Zero All Flat Shade Flags", "Zero All Non-perspective Flags", "Point size", "Line width",
    "clip_window", "Viewport Offset", "Clipper Z min/max clipping planes", "Clipper XY Scaling", "Clipper Z Scale and Offset", "Number of Layers",
    "Tile Binning Mode Cfg", "Tile Rendering Mode Cfg (Common)", "Tile Rendering Mode Cfg (Color)", "Tile Rendering Mode Cfg (ZS Clear Values)",
    "Tile Rendering Mode Cfg (Clear Colors Part1)", "Tile Rendering Mode Cfg (Clear Colors Part2)", "Tile Rendering Mode Cfg (Clear Colors Part3)",
    "Tile Coordinates", "Tile Coordinates Implicit", "Multicore Rendering Supertile Cfg", "Multicore Rendering Tile List Set Base", "Tile List Initial Block Size",
]
STRUCTS = ["GL Shader State Record", "GL Shader State Attribute Record"]
ENUMS = ["Memory Format", "Internal Type", "Internal BPP", "Internal Depth Type", "Render Target Clamp", "Output Image Format", "Decimate Mode", "Dither Mode",
         "Primitive", "Compare Function", "Line Rasterization", "Blend Factor", "Blend Mode"]


def ident(name, upper_first=True):
    words = [w for w in re.split(r"[^0-9A-Za-z]+", name) if w]
    return "".join(w[0].upper() + w[1:] if upper_first else w.lower() for w in words)


def snake(name):
    return "_".join(w.lower() for w in re.split(r"[^0-9A-Za-z]+", name) if w)


def valid(e):
    lo, hi = e.attrib.get("min_ver"), e.attrib.get("max_ver")
    return (lo is None or int(lo) <= VERSION) and (hi is None or int(hi) >= VERSION)


def start_of(text):
    return int(text[:-1]) * 8 if text.endswith("b") else int(text)


def main():
    root = ET.parse(sys.argv[1]).getroot()
    out = ["// Generated by scripts/gen_v3d_packets.py from Mesa's v3d_packet.xml for V3D %d.%d. Do not edit." % (VERSION // 10, VERSION % 10), ""]
    chosen = {}
    for e in root:
        n = e.attrib.get("name")
        if e.tag == "packet" and n in PACKETS and valid(e):
            chosen[("packet", n)] = e
        elif e.tag == "struct" and n in STRUCTS and valid(e):
            chosen[("struct", n)] = e
        elif e.tag == "enum" and n in ENUMS and valid(e):
            chosen[("enum", n)] = e
    out.append("namespace v3d_pkt {")
    for (kind, name), e in sorted(chosen.items(), key=lambda kv: (kv[0][0] != "enum", kv[0][1])):
        ns = snake(name)
        if kind == "enum":
            out.append("namespace %s {" % ns)
            for v in e:
                if v.tag == "value" and valid(v):
                    out.append("constexpr uint32_t k%s = %s;" % (ident(v.attrib["name"]), v.attrib["value"]))
            out.append("}")
            continue
        shift = 8 if kind == "packet" else 0
        fields = []
        for f in e:
            if f.tag != "field" or not valid(f):
                continue
            start = start_of(f.attrib["start"]) + shift
            size = int(f.attrib["size"])
            fields.append((ident(f.attrib["name"]), start, size, f.attrib.get("minus_one") == "true", f.attrib["type"], f.attrib.get("default")))
        length = max([(s + z - 1) // 8 for _, s, z, _, _, _ in fields] + [0]) + 1 if kind == "packet" else max((s + z - 1) // 8 for _, s, z, _, _, _ in fields) + 1
        out.append("namespace %s {" % ns)
        if kind == "packet":
            out.append("constexpr V3dPacketInfo kInfo{%s, %d};" % (e.attrib["code"], length))
        else:
            out.append("constexpr uint32_t kBytes = %d;" % length)
        for fname, start, size, minus_one, ftype, default in fields:
            out.append("constexpr V3dField k%s{%d, %d, %s, %d};  // %s" % (fname, start, size, "true" if minus_one else "false", (start - shift) % 32, ftype))
            if default is not None:
                out.append("constexpr uint32_t k%sDefault = %s;" % (fname, default))
        out.append("}")
    out.append("}  // namespace v3d_pkt")
    print("\n".join(out))


main()
