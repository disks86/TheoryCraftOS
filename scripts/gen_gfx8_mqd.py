#!/usr/bin/env python3
"""Generates AmdGfx8MqdLayout.inc: where each field of the GFX 8 memory queue descriptor (struct vi_mqd of vi_structs.h) is, as a dword index.

  gen_gfx8_mqd.py out.inc source.cpp vi_structs.h gfx_8_0_d.h

The descriptor is an array of 32-bit words (the script refuses a struct that has anything else). Only the names the source file uses (kMqd_<field>) are emitted, plus
the size of the descriptor and of vi_mqd_allocation (the descriptor followed by the write-back words and the dynamic masks). It also checks what the driver relies on when it
copies the descriptor into the hardware queue registers (gfx_v8_0_mqd_commit): from cp_mqd_base_addr_lo to cp_hqd_error, the field for register mmCP_HQD_X sits at the same
distance from the first field as the register from mmCP_MQD_BASE_ADDR.
"""
import re
import sys


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    out, source, structs, regs = sys.argv[1:]
    text = open(structs).read()
    m = re.search(r'struct vi_mqd \{(.*?)\};', text, re.S)
    fields = []
    for line in m.group(1).split('\n'):
        line = re.sub(r'/\*.*?\*/', '', line).strip()
        if not line:
            continue
        mm = re.fullmatch(r'uint32_t (\w+)(?:\[(\d+)\])?;', line)
        if not mm:
            sys.exit('not a 32-bit field: ' + line)
        if mm.group(2):   # an array (reserved_t[256] at the end): its words are named name_0.. so the layout stays flat
            fields += [f'{mm.group(1)}_{k}' for k in range(int(mm.group(2)))]
        else:
            fields.append(mm.group(1))
    index = {name: i for i, name in enumerate(fields)}
    alloc = re.search(r'struct vi_mqd_allocation \{(.*?)\};', text, re.S).group(1)
    extra = [re.sub(r'/\*.*?\*/', '', l).strip() for l in alloc.split('\n')]
    extra = [l for l in extra if l and not l.startswith('struct vi_mqd ')]
    assert all(re.fullmatch(r'uint32_t \w+;', l) for l in extra), extra
    # the register order check
    reg = {n: int(v, 16) for n, v in re.findall(r'#define (mm\w+)\s+(0x[0-9a-fA-F]+)', open(regs).read())}
    base_field, last_field = 'cp_mqd_base_addr_lo', 'cp_hqd_error'
    base = index[base_field]
    checked = 0
    for name in fields[base:index[last_field] + 1]:
        r = 'mm' + re.sub(r'_lo$', '', name).upper()
        if name.endswith('_hi'):
            r = 'mm' + name.upper()
        if r in reg:
            if reg[r] - reg['mmCP_MQD_BASE_ADDR'] != index[name] - base:
                sys.exit(f'{name} is at {index[name] - base}, register {r} is at {reg[r] - reg["mmCP_MQD_BASE_ADDR"]}')
            checked += 1
    code = re.sub(r'#define.*', '', open(source).read())
    used = sorted(set(re.findall(r'\bkMqd_(\w+)\b', code)))
    missing = [u for u in used if u not in index and u not in ('Dwords', 'AllocationDwords', 'WptrPollMem', 'RptrReportMem', 'DynamicCuMask', 'DynamicRbMask')]
    if missing:
        sys.exit('not in struct vi_mqd: ' + ', '.join(missing))
    with open(out, 'w') as f:
        f.write('// Generated by scripts/gen_gfx8_mqd.py from the Linux kernel headers vi_structs.h and gfx_8_0_d.h\n')
        f.write('// (Copyright Advanced Micro Devices, Inc.; MIT license). Do not edit by hand: change ' + source.split('/')[-1] + ' and run the script again.\n\n')
        f.write(f'constexpr uint32_t kMqd_Dwords = {len(fields)};   // sizeof(struct vi_mqd) / 4\n')
        f.write(f'constexpr uint32_t kMqd_AllocationDwords = {len(fields) + len(extra)};   // sizeof(struct vi_mqd_allocation) / 4\n')
        f.write(f'constexpr uint32_t kMqd_WptrPollMem = {len(fields)}, kMqd_RptrReportMem = {len(fields) + 1}, kMqd_DynamicCuMask = {len(fields) + 2}, kMqd_DynamicRbMask = {len(fields) + 3};\n')
        for u in used:
            if u in index:
                f.write(f'constexpr uint32_t kMqd_{u} = {index[u]};\n')
    print(f'{len(used)} fields, {len(fields)} words, {checked} registers matched')


main()
