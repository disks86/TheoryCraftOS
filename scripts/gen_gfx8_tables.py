#!/usr/bin/env python3
"""Generates AmdGfx8Tables.inc: the two tables of the GFX 8 (VI) driver that are too long to type in, taken from the Linux kernel sources.

  gen_gfx8_tables.py out.inc gfx_v8_0.c clearstate_vi.h gfx_8_0_enum.h gfx_8_0_sh_mask.h

- the tile mode and macrotile mode tables of gfx_v8_0_tiling_mode_table_init for CHIP_FIJI / CHIP_VEGAM: the C expressions of the driver are compiled with its own macros
  and AMD's enum and shift headers, and the 32 + 16 values are printed;
- the clear-state context register defaults, vi_cs_data of clearstate_vi.h: one extent per run of registers (first register, count, offset into the data) and the data.
Needs a C compiler (cc).
"""
import os
import re
import subprocess
import sys
import tempfile


def tiling(src, enum_h, mask_h):
    start = src.index('gfx_v8_0_tiling_mode_table_init(struct amdgpu_device *adev)')
    case = src.index('case CHIP_FIJI:\n\tcase CHIP_VEGAM:', start)
    end = src.index('for (reg_offset = 0; reg_offset < num_tile_mode_states; reg_offset++)\n\t\t\tWREG32', case)
    block = src[case + len('case CHIP_FIJI:\n\tcase CHIP_VEGAM:'):end]
    macros = '\n'.join(l for l in src.split('\n') if re.match(r'#define (ARRAY_MODE|PIPE_CONFIG|TILE_SPLIT|MICRO_TILE_MODE_NEW|SAMPLE_SPLIT|BANK_WIDTH|BANK_HEIGHT|MACRO_TILE_ASPECT|NUM_BANKS)\(', l))
    prog = f'''#include <stdio.h>
#include <stdint.h>
typedef uint32_t u32;
#include "{enum_h}"
#include "{mask_h}"
{macros}
int main(void) {{
  u32 modearray[32] = {{0}}, mod2array[16] = {{0}};
{block}
  for (int i = 0; i < 32; i++) printf("T %08x\\n", modearray[i]);
  for (int i = 0; i < 16; i++) printf("M %08x\\n", mod2array[i]);
  return 0;
}}
'''
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, 't.c')
        open(c, 'w').write(prog)
        subprocess.check_call(['cc', '-w', '-o', os.path.join(d, 't'), c])
        out = subprocess.check_output([os.path.join(d, 't')]).decode()
    t = [int(l.split()[1], 16) for l in out.split('\n') if l.startswith('T ')]
    m = [int(l.split()[1], 16) for l in out.split('\n') if l.startswith('M ')]
    return t, m


def clear_state(text):
    arrays = {}
    for name, body in re.findall(r'static const unsigned int (vi_SECT_CONTEXT_def_\d+)\[\]\s*=\s*\{(.*?)\};', text, re.S):
        arrays[name] = [int(v, 16) if v.startswith('0x') else int(v) for v in re.findall(r'^\s*(0x[0-9a-fA-F]+|\d+),', body, re.M)]
    extents = re.findall(r'\{(vi_SECT_CONTEXT_def_\d+),\s*(0x[0-9a-fA-F]+),\s*(\d+)\s*\}', text)
    data, table = [], []
    for name, index, count in extents:
        assert len(arrays[name]) == int(count), name
        table.append((int(index, 16), int(count), len(data)))
        data += arrays[name]
    return table, data


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    out, src, clear, enum_h, mask_h = sys.argv[1:]
    t, m = tiling(open(src).read(), os.path.abspath(enum_h), os.path.abspath(mask_h))
    table, data = clear_state(open(clear).read())
    with open(out, 'w') as f:
        f.write('// Generated by scripts/gen_gfx8_tables.py from the Linux kernel sources gfx_v8_0.c, clearstate_vi.h, gfx_8_0_enum.h and gfx_8_0_sh_mask.h\n')
        f.write('// (Copyright Advanced Micro Devices, Inc.; MIT license). Do not edit by hand.\n\n')
        f.write('// GB_TILE_MODE0..31 and GB_MACROTILE_MODE0..15 of the Fiji and VEGAM (gfx_v8_0_tiling_mode_table_init).\n')
        f.write('constexpr uint32_t kTileModes[32] = {\n' + ''.join(f'    0x{v:08X},\n' for v in t) + '};\n')
        f.write('constexpr uint32_t kMacrotileModes[16] = {\n' + ''.join(f'    0x{v:08X},\n' for v in m) + '};\n\n')
        f.write('// vi_cs_data: the SECT_CONTEXT extents (first register, number of registers, offset into kClearStateData) and the register values.\n')
        f.write('struct ClearStateExtent {\n  uint32_t first_register, count, offset;\n};\n')
        f.write('constexpr ClearStateExtent kClearStateExtents[] = {\n' + ''.join(f'    {{0x{a:08X}, {b}, {c}}},\n' for a, b, c in table) + '};\n')
        f.write(f'constexpr uint32_t kClearStateData[{len(data)}] = {{\n')
        for i in range(0, len(data), 8):
            f.write('    ' + ', '.join(f'0x{v:08X}' for v in data[i:i + 8]) + ',\n')
        f.write('};\n')
    print(f'{len(t)} tile modes, {len(m)} macrotile modes, {len(table)} extents, {len(data)} clear state values')


main()
