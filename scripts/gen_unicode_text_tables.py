def is_hangul(c):
    return 0xAC00 <= c <= 0xD7A3

out = []
w = out.append
w(LICENSE)
w("// GENERATED by scripts/gen_unicode_text_tables.py from Unicode %s. Do not edit." % ud.unidata_version)
w("#pragma once")
w("#include <stdint.h>")
w("")
w("namespace script {")
w("namespace unicode_tables {")
w("")

def pairs(name, items):
    w("inline constexpr uint32_t %s[][2] = {" % name)
    line = []
    for a, b in items:
        line.append("{0x%X,0x%X}" % (a, b))
        if len(line) == 8:
            w("  " + ",".join(line) + ",")
            line = []
    if line:
        w("  " + ",".join(line) + ",")
    w("};")
    w("inline constexpr uint32_t %sCount = %d;" % (name, len(items)))
    w("")

# 1:1 case mappings (the full mapping of one code point to one code point)
upper, lower = [], []
upper_multi, lower_multi = [], []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    ch = chr(c)
    u, l = ch.upper(), ch.lower()
    if len(u) == 1:
        if u != ch:
            upper.append((c, ord(u)))
    else:
        upper_multi.append((c, [ord(x) for x in u]))
    if len(l) == 1:
        if l != ch:
            lower.append((c, ord(l)))
    else:
        lower_multi.append((c, [ord(x) for x in l]))
pairs("kUpper", upper)
pairs("kLower", lower)

def multi(name, items):
    w("inline constexpr uint32_t %s[][4] = {   // code point, then up to three code points (0 pads)" % name)
    for c, seq in items:
        seq = seq + [0] * (3 - len(seq))
        w("  {0x%X,0x%X,0x%X,0x%X}," % (c, seq[0], seq[1], seq[2]))
    w("};")
    w("inline constexpr uint32_t %sCount = %d;" % (name, len(items)))
    w("")
multi("kUpperMulti", upper_multi)
multi("kLowerMulti", lower_multi)

# characters that are "cased" or "case ignorable" for the final sigma rule
cased = [c for c in range(0x110000) if (chr(c).lower() != chr(c) or chr(c).upper() != chr(c)) or ud.category(chr(c)) in ("Lu", "Ll", "Lt")]
def ranges(values):
    values = sorted(set(values))
    result = []
    start = prev = None
    for v in values:
        if start is None:
            start = prev = v
        elif v == prev + 1:
            prev = v
        else:
            result.append((start, prev))
            start = prev = v
    if start is not None:
        result.append((start, prev))
    return result
def range_table(name, items):
    w("inline constexpr uint32_t %s[][2] = {" % name)
    line = []
    for a, b in items:
        line.append("{0x%X,0x%X}" % (a, b))
        if len(line) == 8:
            w("  " + ",".join(line) + ",")
            line = []
    if line:
        w("  " + ",".join(line) + ",")
    w("};")
    w("inline constexpr uint32_t %sCount = %d;" % (name, len(items)))
    w("")
range_table("kCased", ranges(cased))
ignorable = [c for c in range(0x110000) if ud.category(chr(c)) in ("Mn", "Me", "Cf", "Lm", "Sk") or chr(c) in "'.:·‘’․‧︓﹒﹕＇．："]
range_table("kCaseIgnorable", ranges(ignorable))

# canonical combining classes
ccc = [(c, ud.combining(chr(c))) for c in range(0x110000) if ud.combining(chr(c))]
pairs("kCombining", ccc)

# full decompositions (canonical for NFD, compatibility for NFKD), Hangul left out
def decomp_table(prefix, form):
    entries = []
    pool = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF or is_hangul(c):
            continue
        ch = chr(c)
        d = ud.normalize(form, ch)
        if d != ch:
            entries.append((c, len(pool), len(d)))
            pool.extend(ord(x) for x in d)
    w("inline constexpr uint32_t %s[][3] = {   // code point, offset in the pool, length" % (prefix))
    line = []
    for e in entries:
        line.append("{0x%X,%d,%d}" % e)
        if len(line) == 6:
            w("  " + ",".join(line) + ",")
            line = []
    if line:
        w("  " + ",".join(line) + ",")
    w("};")
    w("inline constexpr uint32_t %sCount = %d;" % (prefix, len(entries)))
    w("inline constexpr uint32_t %sPool[] = {" % prefix)
    line = []
    for p in pool:
        line.append("0x%X" % p)
        if len(line) == 12:
            w("  " + ",".join(line) + ",")
            line = []
    if line:
        w("  " + ",".join(line) + ",")
    w("};")
    w("")
decomp_table("kCanonicalDecomposition", "NFD")
decomp_table("kCompatibilityDecomposition", "NFKD")

# primary composites: pairs that compose (not excluded)
comp = []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF or is_hangul(c):
        continue
    ch = chr(c)
    d = ud.decomposition(ch)
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2:
        continue
    if ud.normalize("NFC", ch) != ch:
        continue   # excluded from composition
    comp.append((parts[0], parts[1], c))
comp.sort()
w("inline constexpr uint32_t kComposition[][3] = {   // first, second, composite (sorted)")
line = []
for e in comp:
    line.append("{0x%X,0x%X,0x%X}" % e)
    if len(line) == 6:
        w("  " + ",".join(line) + ",")
        line = []
if line:
    w("  " + ",".join(line) + ",")
w("};")
w("inline constexpr uint32_t kCompositionCount = %d;" % len(comp))
w("")
w("}  // namespace unicode_tables")
w("}  // namespace script")
sys.stdout.write("\n".join(out) + "\n")
