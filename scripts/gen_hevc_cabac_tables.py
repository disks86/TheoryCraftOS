#!/usr/bin/env python3
"""Makes H265CabacInit.inc: the initial values of the CABAC context variables of H.265 (ITU-T H.265 Tables 9-5 to 9-37), one row per initType (0: I slices, 1 and 2:
P and B slices), laid out the way H265Cabac.hpp numbers its contexts. The numbers are read from a copy of FFmpeg's libavcodec/hevc_cabac.c (init_values), which lists
them for the three init types in its own order; this script only re-orders them.

  gen_hevc_cabac_tables.py out.inc hevc_cabac.c
"""
import re
import sys

# (my name, count, ffmpeg offset) in my order. Elements FFmpeg lays out with spare entries (cu_qp_delta has three, intra_chroma_pred_mode two, the mvd flags two each)
# are read from the entry the standard uses.
LAYOUT = [
    ('SaoMerge', 1, 0), ('SaoType', 1, 1), ('SplitCu', 3, 2), ('TransquantBypass', 1, 5), ('Skip', 3, 6), ('CuQpDelta', 2, 9), ('PredMode', 1, 12),
    ('PartMode', 4, 13), ('PrevIntraLuma', 1, 17), ('ChromaPred', 1, 18), ('MergeFlag', 1, 20), ('MergeIdx', 1, 21), ('InterPredIdc', 5, 22), ('RefIdx', 2, 27),
    ('MvpFlag', 1, 35), ('RqtRootCbf', 1, 36), ('SplitTransform', 3, 37), ('CbfLuma', 2, 40), ('CbfChroma', 4, 42), ('MvdGreater0', 1, 31), ('MvdGreater1', 1, 34),
    ('TransformSkip', 2, 47), ('LastX', 18, 53), ('LastY', 18, 71), ('CodedSubBlock', 4, 89), ('SigCoeff', 42, 93), ('Greater1', 24, 137), ('Greater2', 6, 161),
]


def main():
    out, path = sys.argv[1], sys.argv[2]
    text = open(path).read()
    body = text[text.index('init_values[3]'):]
    body = body[:body.index('};\n\n')]  # up to the end of the three arrays
    # strip comments, split the three initializer blocks
    body = re.sub(r'//[^\n]*', '', body)
    body = body.replace('CNU', '154')
    blocks = re.findall(r'\{([^{}]*)\}', body[body.index('= {') + 3:])
    assert len(blocks) == 3, len(blocks)
    rows = [[int(x) for x in re.findall(r'\d+', b)] for b in blocks]
    assert len(rows[0]) == len(rows[1]) == len(rows[2]), [len(r) for r in rows]
    lines = ['// Generated by scripts/gen_hevc_cabac_tables.py: the initial values of the H.265 CABAC contexts (ITU-T H.265 Tables 9-5 .. 9-37), initType 0, 1, 2.',
             '// Do not edit by hand. Row layout: see the Ctx enumeration in H265Cabac.hpp.', '{']
    for row in rows:
        vals = []
        for name, count, off in LAYOUT:
            vals += row[off:off + count]
        lines.append('  {' + ', '.join(str(v) for v in vals) + '},')
    lines.append('}')
    total = sum(c for _, c, _ in LAYOUT)
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('contexts per row:', total)


main()
