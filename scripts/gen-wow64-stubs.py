"""The exports of a 32-bit library that are not implemented yet (src/Windows/stubs/<dll>.inc), as assembly for i386 (docs/Wow64.md).

The functions of the Windows interfaces are stdcall on i386: the function takes its arguments off the stack, so a stub has to know how many bytes
they are. The 64-bit stubs (stubs.c) need not, and the lists do not say. The sizes are read from the import library of the same DLL that
i686-w64-mingw32 ships (its symbols are named _Function@bytes); a function it does not know, or knows as cdecl, gets a stub that takes nothing off.

Usage: gen-wow64-stubs.py <dll> <stubs.inc[+more.inc]> <result> <nm> <mingw lib folder> <out.S> [<dll>32.implemented]
"""
import os
import re
import subprocess
import sys


def argument_bytes(nm, folder, dll):
    sizes = {}
    library = os.path.join(folder, "lib" + dll.replace("-", "_") + ".a")
    if not os.path.exists(library):
        library = os.path.join(folder, "lib" + dll + ".a")
    if not os.path.exists(library):
        return sizes
    listing = subprocess.run([nm, library], capture_output=True, text=True, check=False).stdout
    for line in listing.splitlines():
        match = re.match(r"^[0-9a-f]+ T _([A-Za-z_][A-Za-z0-9_]*)@(\d+)$", line.strip())
        if match:
            sizes[match.group(1)] = int(match.group(2))
    return sizes


def main():
    dll, stub_list, result, nm, folder, out = sys.argv[1:7]
    implemented = set()      # (names the 32-bit library defines although the list has them: <dll>32.implemented, one a line)
    if len(sys.argv) > 7 and os.path.exists(sys.argv[7]):
        with open(sys.argv[7], encoding="utf-8") as listed:
            implemented = {line.strip() for line in listed if line.strip() and not line.startswith(";")}
    names = []
    for path in stub_list.split("+"):      # (several lists: "a.inc+b.inc")
        with open(path, encoding="utf-8") as source:
            names += [name for name in re.findall(r"^\s*X\(([A-Za-z_][A-Za-z0-9_]*)\)", source.read(), re.M) if name not in names]
    sizes = argument_bytes(nm, folder, dll)
    lines = ["/* Generated by scripts/gen-wow64-stubs.py: the exports of %s.dll that do nothing yet, for i386. */" % dll, ".text"]
    exports = []
    for name in names:
        if name in implemented:
            continue
        size = sizes.get(name)
        symbol = "_%s@%d" % (name, size) if size is not None else "_" + name
        lines += [".globl %s" % symbol, "%s:" % symbol, "  movl $%s, %%eax" % result.rstrip("uU"), "  xorl %edx, %edx", "  ret $%d" % size if size else "  ret"]
        exports.append("%s@%d" % (name, size) if size is not None else name)
    lines.append(".section .drectve")
    for export in exports:
        lines.append('.ascii " -export:%s"' % export)
    with open(out, "w", encoding="utf-8") as target:
        target.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
