#!/usr/bin/env python3
"""Generates a register constants file (AmdVcn1Registers.inc, AmdRavenMemoryRegisters.inc): the register numbers, base indexes and field masks a driver
source file uses, taken from AMD's own headers in the Linux kernel tree so none is typed in by hand.

  gen_vcn1_regs.py out.inc source.cpp header.h [header.h ...]

  AmdVcn1.cpp:         vcn_1_0_offset.h vcn_1_0_sh_mask.h
  AmdVcn1Ring.cpp:     vcn_1_0_offset.h vcn_1_0_sh_mask.h
  AmdRavenMemory.cpp:  gc_9_1_offset.h mmhub_9_1_offset.h mmhub_9_1_sh_mask.h nbio_7_0_offset.h
  (all under drivers/gpu/drm/amd/include/asic_reg/ in the kernel tree)

Only the names the source file mentions are emitted. A name that is in none of the headers and is not defined in the source file itself (above its include of
the generated file) is an error.
"""
import os
import re
import sys


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out, source, headers = sys.argv[1], sys.argv[2], sys.argv[3:]
    text = open(source).read()
    code = '\n'.join(l for l in text.split('\n') if not l.lstrip().startswith('#define'))   # the macro definitions are not uses
    marker = re.search(r'#include "[^"]*Registers\.inc"', text)
    local = set(re.findall(r'constexpr uint32_t (\w+)\s*=', text[:marker.start()] if marker else text))

    # Several headers can define the same register name for different blocks (MC_VM_FB_OFFSET is in both the graphics and the memory hub headers, at different
    # numbers). A name defined with different values must be assigned to one header by a directive in the source file:  // regs-from: NAME header.h
    defined = {}   # name -> {header basename: value}
    for path in headers:
        for line in open(path):
            m = re.match(r'#define\s+(\w+)\s+(0x[0-9A-Fa-f]+|\d+)[Ll]?\b', line)
            if m:
                defined.setdefault(m.group(1), {})[os.path.basename(path)] = int(m.group(2), 0)
    directives = dict(re.findall(r'//\s*regs-from:\s*(\w+)\s+(\S+)', text))
    values = {}
    ambiguous = []
    for name, by_header in defined.items():
        if len(set(by_header.values())) == 1:
            values[name] = next(iter(by_header.values()))
        elif name in directives and directives[name] in by_header:
            values[name] = by_header[directives[name]]
        else:
            ambiguous.append((name, by_header))

    used = set()
    for name in re.findall(r'\b(mm[A-Z][A-Z0-9_]*)\b', code):
        if name.endswith('_BASE_IDX'):
            name = name[:-len('_BASE_IDX')]
        used.add(name)
    for name in re.findall(r'\b([A-Z][A-Z0-9_]*__[A-Z0-9_]+)\b', code):
        used.add(name)
    # REG_SET_FIELD(orig, REG, FIELD, v) pastes REG__FIELD__SHIFT / REG__FIELD_MASK itself
    for reg, field in re.findall(r'REG_SET_FIELD\([^,]+,\s*(\w+),\s*(\w+),', code):
        used.add(f'{reg}__{field}__SHIFT')
        used.add(f'{reg}__{field}_MASK')

    for name, by_header in ambiguous:
        base = name[:-len('_BASE_IDX')] if name.endswith('_BASE_IDX') else name
        if base in used:
            sys.exit(f'{name} is defined differently in {sorted(by_header)}: say which one with a "// regs-from: {base} <header>" line in the source')
    lines = []
    missing = []
    for name in sorted(used):
        if name in local:
            continue
        if name.startswith('mm'):
            if name not in values or name + '_BASE_IDX' not in values:
                missing.append(name)
                continue
            lines.append(f'constexpr uint32_t {name} = 0x{values[name]:08X};')
            lines.append(f'constexpr uint32_t {name}_BASE_IDX = {values[name + "_BASE_IDX"]};')
        else:
            if name not in values:
                missing.append(name)
                continue
            lines.append(f'constexpr uint32_t {name} = 0x{values[name]:08X};')
    if missing:
        sys.exit('not found in the headers and not defined in the source: ' + ', '.join(missing))

    with open(out, 'w') as f:
        f.write('// Generated by scripts/gen_vcn1_regs.py from the Linux kernel headers ' + ', '.join(os.path.basename(h) for h in headers) + '\n')
        f.write('// (Copyright Advanced Micro Devices, Inc.; MIT license). Register numbers are dwords; *_BASE_IDX picks the segment base of the register block.\n')
        f.write('// Do not edit by hand: change ' + os.path.basename(source) + ' and run the script again.\n\n')
        f.write('\n'.join(lines) + '\n')
    print(f'{len(lines)} constants for {len(used) - len(local & used)} names')


main()
