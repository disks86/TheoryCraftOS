#!/usr/bin/env python3
"""Generates src/Hardware/VideoCodec/AMD/AmdVcn1Registers.inc: the register numbers, base indexes and field masks the VCN 1.0 driver (AmdVcn1.cpp) uses,
taken from AMD's own headers in the Linux kernel tree so none is typed in by hand.

  gen_vcn1_regs.py vcn_1_0_offset.h vcn_1_0_sh_mask.h AmdVcn1.cpp AmdVcn1Registers.inc

  drivers/gpu/drm/amd/include/asic_reg/vcn/vcn_1_0_offset.h
  drivers/gpu/drm/amd/include/asic_reg/vcn/vcn_1_0_sh_mask.h

Only the names AmdVcn1.cpp mentions are emitted. A name that is in neither header and is not defined in AmdVcn1.cpp itself is an error.
"""
import re
import sys


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    offset_h, mask_h, source, out = sys.argv[1:]
    text = open(source).read()
    code = '\n'.join(l for l in text.split('\n') if not l.lstrip().startswith('#define'))   # the macro definitions are not uses
    local = set(re.findall(r'constexpr uint32_t (\w+)\s*=', text.split('#include "Hardware/VideoCodec/AMD/AmdVcn1Registers.inc"')[0]))

    values = {}
    for path in (offset_h, mask_h):
        for line in open(path):
            m = re.match(r'#define\s+(\w+)\s+(0x[0-9A-Fa-f]+|\d+)[Ll]?\b', line)
            if m:
                values[m.group(1)] = int(m.group(2), 0)

    used = set()
    for name in re.findall(r'\b(mm[A-Z][A-Z0-9_]*)\b', code):
        if name.endswith('_BASE_IDX'):
            name = name[:-len('_BASE_IDX')]
        used.add(name)
    for name in re.findall(r'\b([A-Z][A-Z0-9_]*__[A-Z0-9_]+)\b', code):
        used.add(name)
    # REG_SET_FIELD(orig, REG, FIELD, v) pastes REG__FIELD__SHIFT / REG__FIELD_MASK itself
    for reg, field in re.findall(r'REG_SET_FIELD\([^,]+,\s*(\w+),\s*(\w+),', code):
        used.add(f'{reg}__{field}__SHIFT')
        used.add(f'{reg}__{field}_MASK')

    lines = []
    missing = []
    for name in sorted(used):
        if name in local:
            continue
        if name.startswith('mm'):
            if name not in values or name + '_BASE_IDX' not in values:
                missing.append(name)
                continue
            lines.append(f'constexpr uint32_t {name} = 0x{values[name]:08X};')
            lines.append(f'constexpr uint32_t {name}_BASE_IDX = {values[name + "_BASE_IDX"]};')
        else:
            if name not in values:
                missing.append(name)
                continue
            lines.append(f'constexpr uint32_t {name} = 0x{values[name]:08X};')
    if missing:
        sys.exit('not found in the headers and not defined in the source: ' + ', '.join(missing))

    with open(out, 'w') as f:
        f.write('// Generated by scripts/gen_vcn1_regs.py from the Linux kernel headers drivers/gpu/drm/amd/include/asic_reg/vcn/vcn_1_0_offset.h and vcn_1_0_sh_mask.h\n')
        f.write('// (Copyright 2018 Advanced Micro Devices, Inc.; MIT license). Register numbers are dwords; *_BASE_IDX picks the segment base of the UVD register block.\n')
        f.write('// Do not edit by hand: change AmdVcn1.cpp and run the script again.\n\n')
        f.write('\n'.join(lines) + '\n')
    print(f'{len(lines)} constants for {len(used) - len(local & used)} names')


main()
