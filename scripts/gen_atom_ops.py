#!/usr/bin/env python3
"""Generates the opcode table of the AtomBIOS interpreter (src/Hardware/GraphicsProcessingUnit/AMD/AtomBiosOps.inc) from the Linux driver's opcode_table in atom.c.

  gen_atom_ops.py path/to/atom.c out.inc

(kernel tag v6.12, drivers/gpu/drm/amd/amdgpu/atom.c). Each row is {operation, argument}; the argument is the kind of operand (register, parameter space, workspace, ...), the jump
condition, the delay unit or the port, whatever that operation takes from the table. The operation names are mapped to AtomOp; a name this script does not know is an error.
"""
import re
import sys

OPS = {
    'NULL': 'None', 'atom_op_move': 'Move', 'atom_op_and': 'And', 'atom_op_or': 'Or', 'atom_op_shift_left': 'ShiftLeft', 'atom_op_shift_right': 'ShiftRight', 'atom_op_mul': 'Mul',
    'atom_op_div': 'Div', 'atom_op_add': 'Add', 'atom_op_sub': 'Sub', 'atom_op_setport': 'SetPort', 'atom_op_setregblock': 'SetRegBlock', 'atom_op_setfbbase': 'SetFbBase',
    'atom_op_compare': 'Compare', 'atom_op_switch': 'Switch', 'atom_op_jump': 'Jump', 'atom_op_test': 'Test', 'atom_op_delay': 'Delay', 'atom_op_calltable': 'CallTable',
    'atom_op_repeat': 'Repeat', 'atom_op_clear': 'Clear', 'atom_op_nop': 'Nop', 'atom_op_eot': 'Eot', 'atom_op_mask': 'Mask', 'atom_op_postcard': 'PostCard', 'atom_op_beep': 'Beep',
    'atom_op_savereg': 'SaveReg', 'atom_op_restorereg': 'RestoreReg', 'atom_op_setdatablock': 'SetDataBlock', 'atom_op_xor': 'Xor', 'atom_op_shl': 'Shl', 'atom_op_shr': 'Shr',
    'atom_op_debug': 'Debug', 'atom_op_processds': 'ProcessDs', 'atom_op_mul32': 'Mul32', 'atom_op_div32': 'Div32',
}
ARGS = {
    '0': '0', 'ATOM_ARG_REG': '0', 'ATOM_ARG_PS': '1', 'ATOM_ARG_WS': '2', 'ATOM_ARG_FB': '3', 'ATOM_ARG_ID': '4', 'ATOM_ARG_IMM': '5', 'ATOM_ARG_PLL': '6', 'ATOM_ARG_MC': '7',
    'ATOM_COND_ABOVE': '0', 'ATOM_COND_ABOVEOREQUAL': '1', 'ATOM_COND_ALWAYS': '2', 'ATOM_COND_BELOW': '3', 'ATOM_COND_BELOWOREQUAL': '4', 'ATOM_COND_EQUAL': '5',
    'ATOM_COND_NOTEQUAL': '6', 'ATOM_PORT_ATI': '0', 'ATOM_PORT_PCI': '1', 'ATOM_PORT_SYSIO': '2', 'ATOM_UNIT_MICROSEC': '0', 'ATOM_UNIT_MILLISEC': '1',
}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(sys.argv[1]).read()
    m = re.search(r'opcode_table\[ATOM_OP_CNT\] = \{(.*?)\n\};', src, re.S)
    if not m:
        sys.exit('opcode_table not found')
    rows = re.findall(r'\{\s*(\w+),\s*(\w+)\s*\}', m.group(1))
    if len(rows) != 127:
        sys.exit('expected 127 opcodes, found %d' % len(rows))
    out = ['// Generated by scripts/gen_atom_ops.py from the opcode_table of the Linux kernel\'s drivers/gpu/drm/amd/amdgpu/atom.c (Copyright 2008 Advanced Micro Devices, Inc.; MIT license).',
           '// Row n is opcode n: the operation and the argument the table gives it (operand kind, jump condition, delay unit or port). Do not edit by hand.']
    for i, (func, arg) in enumerate(rows):
        if func not in OPS:
            sys.exit('unknown operation ' + func)
        if arg not in ARGS:
            sys.exit('unknown argument ' + arg)
        out.append('{AtomOp::%s, %s},  // %d' % (OPS[func], ARGS[arg], i))
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
    print('%d opcodes' % len(rows))


main()
