#!/usr/bin/env python3
"""Generates AmdVcnMessageLayout.inc: the byte offsets and sizes of the fields of the decode messages the VCN firmware reads (message header, create, decode, AVC, HEVC
picture parameters, feedback header), measured by compiling the structure definitions in Mesa's radeon_vcn_dec.h with a C compiler, so none is typed in by hand.

  gen_vcn_message_layout.py out.inc radeon_vcn_dec.h

The header is untrusted input: it is only compiled (never run on its own), in a temporary directory, and the program built from it is a few lines of offsetof.
"""
import os
import re
import subprocess
import sys
import tempfile

TYPES = [
    ('Index', 'rvcn_dec_message_index_t'),
    ('Header', 'rvcn_dec_message_header_t'),
    ('Create', 'rvcn_dec_message_create_t'),
    ('Decode', 'rvcn_dec_message_decode_t'),
    ('Avc', 'rvcn_dec_message_avc_t'),
    ('Hevc', 'rvcn_dec_message_hevc_t'),
    ('Av1Warp', 'rvcn_dec_warped_motion_params_t'),
    ('Av1TileInfo', 'rvcn_dec_av1_tile_info_t'),
    ('Av1', 'rvcn_dec_message_av1_t'),
    ('Av1SegmentFg', 'rvcn_dec_av1_segment_fg_t'),
    ('Vp9', 'rvcn_dec_message_vp9_t'),
    ('Mpeg2', 'rvcn_dec_message_mpeg2_vld_t'),
    ('DynamicDpb', 'rvcn_dec_message_dynamic_dpb_t'),
    ('Vp9Probs', 'rvcn_dec_vp9_probs_t'),
    ('FeedbackIndex', 'rvcn_dec_feature_index_t'),
    ('Feedback', 'rvcn_dec_feedback_header_t'),
]


DEPENDENCIES = ['rvcn_dec_vp9_nmv_ctx_mask_t', 'rvcn_dec_vp9_nmv_component_t', 'rvcn_dec_transformation_type_e', 'rvcn_dec_film_grain_params_t', 'rvcn_dec_av1_fg_init_buf_t']


def struct_body(text, type_name):
    """The text between the braces of `typedef struct ... { ... } type_name;`, with nested braces kept."""
    end = re.search(r'\}\s*' + re.escape(type_name) + r'\s*;', text)
    if not end:
        sys.exit('type not found: ' + type_name)
    depth, i = 0, end.start()
    while True:
        if text[i] == '}':
            depth += 1
        elif text[i] == '{':
            depth -= 1
            if depth == 0:
                break
        i -= 1
    return text[i + 1:end.start()]


def fields(body):
    out = []
    depth = 0
    for line in body.split('\n'):
        line = re.sub(r'//.*', '', line).strip()
        depth += line.count('{') - line.count('}')
        if depth > 0 or not line or line.startswith('}') and not re.search(r'\w+\s*;', line):
            continue
        m = re.match(r'^(?:\}\s*)?(?:[A-Za-z_][\w ]*?[\s\*])(\w+)(?:\[[^\]]*\])*\s*;$', line)
        if m:
            out.append(m.group(1))
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    out_path, header = sys.argv[1], sys.argv[2]
    text = open(header).read()
    program = ['#include <stddef.h>', '#include <stdio.h>']
    # Only the structures wanted, copied out of the header with the definitions they depend on (the MVC element type).
    mvc = re.search(r'typedef struct \{\s*unsigned short viewOrderIndex;.*?\} radeon_mvcElement_t;', text, re.S)
    program.append(mvc.group(0))
    wanted = []
    # Types the AV1 message is built from, in dependency order (some are anonymous structures or enumerations).
    for name in DEPENDENCIES:
        m = re.search(r'typedef (?:struct|enum) (?:\w+ )?\{' + re.escape(struct_body(text, name)) + r'\} ' + re.escape(name) + r';', text, re.S)
        program.append(m.group(0))
    for tag, name in TYPES:
        m = re.search(r'typedef struct (?:\w+ )?\{' + re.escape(struct_body(text, name)) + r'\} ' + re.escape(name) + r';', text, re.S)
        program.append(m.group(0))
        wanted.append((tag, name, fields(struct_body(text, name))))
    program.append('int main(void) {')
    for tag, name, names in wanted:
        program.append('printf("%s sizeof %%zu\\n", sizeof(%s));' % (tag, name))
        for f in names:
            program.append('printf("%s %s %%zu\\n", offsetof(%s, %s));' % (tag, f, name, f))
    program.append('return 0; }')
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'layout.c')
        exe = os.path.join(tmp, 'layout')
        open(src, 'w').write('\n'.join(program) + '\n')
        subprocess.check_call(['gcc', '-std=gnu11', '-Wall', '-o', exe, src])
        result = subprocess.check_output([exe], text=True)
    lines = ['// Generated by scripts/gen_vcn_message_layout.py from the structures in Mesa\'s radeon_vcn_dec.h (Copyright Advanced Micro Devices, Inc.; MIT license).',
             '// Byte offsets of the fields of the messages the VCN firmware reads. Do not edit by hand; run the script again.', '']
    for row in result.strip().split('\n'):
        tag, field, value = row.split()
        lines.append('constexpr uint32_t k%s_%s = %s;' % (tag, field, value))
    open(out_path, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
