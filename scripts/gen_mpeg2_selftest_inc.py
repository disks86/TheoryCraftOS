#!/usr/bin/env python3
"""Turns an MPEG-2 elementary stream into the self-test stream include AmdVcnSelfTestMpeg2Stream.inc: the stream as a C++ array, cut into one packet per picture (the
sequence and group headers in front of a picture go with it), and where each packet ends.

  gen_mpeg2_selftest_inc.py stream.m2v out.inc

The input is only read, never executed.
"""
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    d = open(sys.argv[1], 'rb').read()
    # Start codes of interest: sequence header B3, group of pictures B8, picture 00. A packet begins at the first of the headers in front of a picture.
    codes = []
    i = d.find(b'\x00\x00\x01')
    while 0 <= i < len(d) - 3:
        codes.append((i, d[i + 3]))
        i = d.find(b'\x00\x00\x01', i + 3)
    starts, pending = [], None
    for pos, code in codes:
        if code in (0xB3, 0xB8) and pending is None:
            pending = pos
        elif code == 0x00:
            starts.append(pending if pending is not None else pos)
            pending = None
    if not starts or starts[0] != 0:
        sys.exit('the stream must start with a sequence header')
    ends = starts[1:] + [len(d)]
    rows = ['    ' + ', '.join('0x%02X' % b for b in d[j:j + 24]) + ',' for j in range(0, len(d), 24)]
    out = ('// Generated by scripts/gen_mpeg2_selftest_inc.py (see scripts/gen_mpeg2_selftest.sh): a 64 x 64 stream of %d pictures (one packet each, in coding order), the stream the\n'
           '// VCN MPEG-2 self-test has the engine decode. Do not edit by hand.\n'
           'constexpr uint32_t kMpeg2SelfTestPictures = %d;\n'
           'constexpr uint32_t kMpeg2SelfTestSize = 64;\n'
           'constexpr uint64_t kMpeg2SelfTestEnds[%d] = {%s};\n'
           'constexpr uint8_t kMpeg2SelfTestStream[%d] = {\n%s\n};\n') % (len(ends), len(ends), len(ends), ', '.join(str(e) for e in ends), len(d), '\n'.join(rows))
    open(sys.argv[2], 'w').write(out)


main()
