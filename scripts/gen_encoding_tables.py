#!/usr/bin/env python3
"""Writes src/Dom/LegacyEncodingTables.inc from the tables of the WHATWG Encoding Standard.

    curl -O https://encoding.spec.whatwg.org/indexes.json -O https://encoding.spec.whatwg.org/encodings.json
    scripts/gen_encoding_tables.py indexes.json encodings.json > src/Dom/LegacyEncodingTables.inc

The order of the encodings is that of encodings.json (the order of the enum Encoding in LegacyEncodings.hpp)."""
import json, sys

indexes = json.load(open(sys.argv[1]))
groups = json.load(open(sys.argv[2]))
encodings = [e for g in groups for e in g['encodings']]
names = [e['name'].lower() for e in encodings]
out = []
w = out.append
w('// Generated by scripts/gen_encoding_tables.py from https://encoding.spec.whatwg.org/indexes.json and encodings.json. Do not edit.')
w('')
w('constexpr uint32_t kEncodingCount = %d;' % len(names))
w('static const char* const kEncodingNames[kEncodingCount] = {%s};' % ', '.join('"%s"' % n for n in names))
labels = sorted((l, i) for i, e in enumerate(encodings) for l in e['labels'])
w('static const char* const kEncodingDisplayNames[kEncodingCount] = {%s};' % ', '.join('"%s"' % e['name'] for e in encodings))
w('struct EncodingLabel { const char* label; uint8_t encoding; };')
w('static const EncodingLabel kEncodingLabels[] = {%s};' % ', '.join('{"%s", %d}' % l for l in labels))

# single byte encodings: a row of 128 code points for the bytes 0x80 to 0xFF
single = [n for n in names if n in indexes and len(indexes[n]) == 128]
w('static const uint16_t kSingleByteRows[%d][128] = {' % len(single))
for n in single:
    w('  {%s},  // %s' % (', '.join('%d' % (v if v is not None else 0xFFFD) for v in indexes[n]), n))
w('};')
rows = []
for n in names:
    key = 'iso-8859-8' if n == 'iso-8859-8-i' else n
    rows.append(single.index(key) if key in single else -1)
w('static const int8_t kSingleByteRowOf[kEncodingCount] = {%s};' % ', '.join(str(r) for r in rows))

def table(name, ctype, values):
    w('static const %s %s[%d] = {' % (ctype, name, len(values)))
    line = ' '
    for v in values:
        item = ' %d,' % (v if v is not None else 0)
        if len(line) + len(item) > 150:
            w(line); line = ' '
        line += item
    w(line); w('};')

table('kIndexIso2022JpKatakana', 'uint16_t', indexes['iso-2022-jp-katakana'])
table('kIndexBig5', 'uint32_t', indexes['big5'])
table('kIndexEucKr', 'uint16_t', indexes['euc-kr'])
table('kIndexGb18030', 'uint16_t', indexes['gb18030'])
table('kIndexJis0208', 'uint16_t', indexes['jis0208'])
table('kIndexJis0212', 'uint16_t', indexes['jis0212'])
w('struct Gb18030Range { uint32_t pointer, code_point; };')
w('static const Gb18030Range kGb18030Ranges[] = {%s};' % ', '.join('{%d, %d}' % (p, c) for p, c in indexes['gb18030-ranges']))
print('\n'.join(out))
