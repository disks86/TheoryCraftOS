#!/usr/bin/env python3
"""Turns an Annex B H.265 stream into AmdVcnSelfTestHevcStream.inc: the bytes as a C++ array and where each picture's access unit ends (before the next picture's
first slice; the parameter sets in front of a picture belong to it).

  gen_hevc_selftest_inc.py stream.h265 out.inc [Name]

`Name` (default Hevc) is the middle of the constants' names: kHevcSelfTestStream, kHevc10SelfTestStream...

The stream is untrusted input only in the sense that it is read, never executed.
"""
import re
import sys


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    name = sys.argv[3] if len(sys.argv) == 4 else 'Hevc'
    with open(sys.argv[1], 'rb') as f:
        d = f.read()
    starts = [m.start() for m in re.finditer(b'\x00\x00\x01', d)]
    cuts, have = [], False
    for k, s in enumerate(starts):
        t = (d[s + 3] >> 1) & 63
        is_slice = t < 32
        first = is_slice and (d[s + 5] & 0x80)
        if first and have:
            cut, j = s, k
            while j > 0 and 32 <= (d[starts[j - 1] + 3] >> 1) & 63 <= 39:
                cut = starts[j - 1]
                j -= 1
            cuts.append(cut)
            have = False
        if is_slice:
            have = True
    ends = cuts + [len(d)]
    rows = ['    ' + ', '.join('0x%02X' % b for b in d[i:i + 24]) + ',' for i in range(0, len(d), 24)]
    out = ('// Generated by scripts/gen_hevc_selftest_inc.py (see scripts/gen_hevc_test_streams.sh): a %d x %d stream of %d pictures made by libx265, the stream the H.265\n'
           '// self-test has the engine decode. Do not edit by hand.\n'
           'constexpr uint32_t k%sSelfTestPictures = %d;\n'
           'constexpr uint32_t k%sSelfTestSize = 64;\n'
           'constexpr uint64_t k%sSelfTestEnds[%d] = {%s};\n'
           'constexpr uint8_t k%sSelfTestStream[%d] = {\n%s\n};\n') % (64, 64, len(ends), name, len(ends), name, name, len(ends), ', '.join(str(e) for e in ends), name, len(d), '\n'.join(rows))
    with open(sys.argv[2], 'w') as f:
        f.write(out)


main()
