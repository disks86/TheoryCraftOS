#!/usr/bin/env python3
"""Generates Vc1Tables.inc: the variable length code tables, scans and constants of SMPTE 421M (VC-1) that the decoder needs for progressive pictures, as plain arrays.

  gen_vc1_tables.py out.inc dir

`dir` holds FFmpeg's libavcodec sources vc1data.c, vc1_vlc_data.h, vc1acdata.h, msmpeg4_vc1_data.c and wmv2data.c, which carry the standard's tables (read only as
numbers; nothing in them is compiled or run).
"""
import re
import sys

ENUMS = {
    'TT_8X8': 0, 'TT_8X4_BOTTOM': 1, 'TT_8X4_TOP': 2, 'TT_8X4': 3, 'TT_4X8_RIGHT': 4, 'TT_4X8_LEFT': 5, 'TT_4X8': 6, 'TT_4X4': 7,
    'MV_PMODE_1MV_HPEL_BILIN': 0, 'MV_PMODE_1MV': 1, 'MV_PMODE_1MV_HPEL': 2, 'MV_PMODE_MIXED_MV': 3, 'MV_PMODE_INTENSITY_COMP': 4,
}


def find_array(text, name):
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^\]]*\]\s*)+=\s*\{', text)
    if not m:
        sys.exit('table not found: ' + name)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[i:j + 1]
    sys.exit('unterminated: ' + name)


def numbers(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    body = re.sub(r'//.*', '', body)
    out = []
    for tok in re.findall(r'[A-Za-z_][A-Za-z_0-9]*|-?0[xX][0-9a-fA-F]+|-?\d+', body):
        if tok in ENUMS:
            out.append(ENUMS[tok])
        elif re.match(r'-?0[xX]', tok):
            out.append(int(tok, 16))
        elif re.match(r'-?\d+$', tok):
            out.append(int(tok))
        else:
            sys.exit('unknown token ' + tok)
    return out


def rows(body):
    """The top-level groups inside the outer braces, each as a flat list of numbers."""
    body = body.strip()[1:-1]
    groups, depth, start = [], 0, 0
    for i, ch in enumerate(body):
        if ch == '{':
            if depth == 0:
                start = i
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                groups.append(numbers(body[start:i + 1]))
    return groups


def padded(src, name, width, count, wrap=False):
    """A table of `count` rows whose rows may be shorter than `width` numbers (the rest of a row is zeros), as one flat list."""
    flat = []
    r = rows(find_array(src, name))
    if len(r) != count:
        sys.exit('%s: %d rows' % (name, len(r)))
    for row in r:
        if len(row) > width:
            sys.exit('%s: row too long' % name)
        flat += row + [0] * (width - len(row))
    return [v & 0xFF for v in flat] if wrap else flat


def emit(out, ctype, cname, values, dims, per_line=16):
    total = 1
    for d in dims:
        total *= d
    if len(values) != total:
        sys.exit('%s: %d values, expected %d' % (cname, len(values), total))
    out.append('constexpr %s %s[%d] = {' % (ctype, cname, total))
    for i in range(0, len(values), per_line):
        out.append('    ' + ', '.join(str(v) for v in values[i:i + per_line]) + ',')
    out.append('};')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    d = sys.argv[2]
    rd = lambda n: open(d + '/' + n).read()
    data, vlc, acd, msm, wmv = rd('vc1data.c'), rd('vc1_vlc_data.h'), rd('vc1acdata.h'), rd('msmpeg4_vc1_data.c'), rd('wmv2data.c')
    out = ['// Generated by scripts/gen_vc1_tables.py from the tables of SMPTE 421M (as carried by FFmpeg\'s VC-1 sources). Do not edit by hand.', '']

    def table(src, name, ctype, cname, dims, per_line=16):
        emit(out, ctype, cname, numbers(find_array(src, name)), dims, per_line)

    out.append('// Bitplane coding: IMODE, the 2 bit and the 6 bit modes.')
    table(vlc, 'vc1_imode_codes', 'uint8_t', 'kImodeCode', [7])
    table(vlc, 'vc1_imode_bits', 'uint8_t', 'kImodeBits', [7])
    table(vlc, 'vc1_norm2_codes', 'uint8_t', 'kNorm2Code', [4])
    table(vlc, 'vc1_norm2_bits', 'uint8_t', 'kNorm2Bits', [4])
    table(vlc, 'vc1_norm6_codes', 'uint16_t', 'kNorm6Code', [64])
    table(vlc, 'vc1_norm6_bits', 'uint8_t', 'kNorm6Bits', [64])
    out.append('// CBPCY of P and B macroblocks (four tables), indexed by the pattern; the transform type tables (three each: by quantizer range); the motion vector differences (four).')
    table(vlc, 'vc1_cbpcy_p_codes', 'uint16_t', 'kCbpcyCode', [4, 64])
    table(vlc, 'vc1_cbpcy_p_bits', 'uint8_t', 'kCbpcyBits', [4, 64])
    table(vlc, 'vc1_ttmb_codes', 'uint16_t', 'kTtmbCode', [3, 16])
    table(vlc, 'vc1_ttmb_bits', 'uint8_t', 'kTtmbBits', [3, 16])
    table(vlc, 'vc1_ttblk_codes', 'uint8_t', 'kTtblkCode', [3, 8])
    table(vlc, 'vc1_ttblk_bits', 'uint8_t', 'kTtblkBits', [3, 8])
    table(vlc, 'vc1_subblkpat_codes', 'uint8_t', 'kSubblkpatCode', [3, 15])
    table(vlc, 'vc1_subblkpat_bits', 'uint8_t', 'kSubblkpatBits', [3, 15])
    table(vlc, 'vc1_mv_diff_codes', 'uint16_t', 'kMvDiffCode', [4, 73])
    table(vlc, 'vc1_mv_diff_bits', 'uint8_t', 'kMvDiffBits', [4, 73])
    out.append('// The eight coefficient tables: (code, length) of each of the 185 run/level pairs and the escape; then what each pair means.')
    ac = padded(vlc, 'vc1_ac_tables', 186 * 2, 8)
    emit(out, 'uint32_t', 'kAcCode', ac[0::2], [8, 186])
    emit(out, 'uint8_t', 'kAcBits', ac[1::2], [8, 186])
    sizes = numbers(find_array(vlc, 'ff_vc1_ac_sizes'))
    emit(out, 'uint8_t', 'kAcSize', sizes, [8]) if max(sizes) < 256 else sys.exit('size')
    table(acd, 'vc1_last_decode_table', 'uint8_t', 'kAcLastIndex', [8])
    idx = padded(acd, 'vc1_index_decode_table', 185 * 2, 8)
    emit(out, 'uint8_t', 'kAcRun', idx[0::2], [8, 185])
    emit(out, 'uint8_t', 'kAcLevel', idx[1::2], [8, 185])
    emit(out, 'uint8_t', 'kAcDeltaLevel', padded(acd, 'vc1_delta_level_table', 31, 8, True), [8, 31])
    emit(out, 'uint8_t', 'kAcLastDeltaLevel', padded(acd, 'vc1_last_delta_level_table', 44, 8, True), [8, 44])
    emit(out, 'uint8_t', 'kAcDeltaRun', padded(acd, 'vc1_delta_run_table', 57, 8, True), [8, 57])
    emit(out, 'uint8_t', 'kAcLastDeltaRun', padded(acd, 'vc1_last_delta_run_table', 10, 8, True), [8, 10])
    out.append('// Intra macroblock CBPCY (I pictures), the DC differences ([table][luma / chroma][index]: code, length), and the zigzag scans of 8x8 blocks (four, by use).')
    mb = numbers(find_array(msm, 'ff_msmp4_mb_i_table'))
    emit(out, 'uint16_t', 'kIntraCbpcyCode', mb[0::2], [64])
    emit(out, 'uint8_t', 'kIntraCbpcyBits', mb[1::2], [64])
    dc = numbers(find_array(msm, 'ff_msmp4_dc_tables'))
    emit(out, 'uint32_t', 'kDcCode', dc[0::2], [2, 2, 120])
    emit(out, 'uint8_t', 'kDcBits', dc[1::2], [2, 2, 120])
    table(msm, 'ff_wmv1_scantable', 'uint8_t', 'kScan8x8', [4, 64], 16)
    out.append('// Scans of the 8x4 and 4x8 sub-blocks: Simple and Main profile (WMV2 tables A and B), Advanced profile; and the 4x4 scan.')
    table(wmv, 'ff_wmv2_scantableA', 'uint8_t', 'kScan8x4Main', [32])
    table(wmv, 'ff_wmv2_scantableB', 'uint8_t', 'kScan4x8Main', [32])
    table(data, 'ff_vc1_adv_progressive_8x4_zz', 'uint8_t', 'kScan8x4Adv', [32])
    table(data, 'ff_vc1_adv_progressive_4x8_zz', 'uint8_t', 'kScan4x8Adv', [32])
    table(data, 'ff_vc1_simple_progressive_4x4_zz', 'uint8_t', 'kScan4x4', [16])
    out.append('// Quantizer and picture level constants.')
    table(data, 'ff_vc1_ttblk_to_tt', 'uint8_t', 'kTtblkToTt', [3, 8])
    table(data, 'ff_vc1_ttfrm_to_tt', 'uint8_t', 'kTtfrmToTt', [4])
    table(data, 'ff_vc1_mv_pmode_table', 'uint8_t', 'kMvPmodeTable', [2, 5])
    table(data, 'ff_vc1_mv_pmode_table2', 'uint8_t', 'kMvPmodeTable2', [2, 4])
    table(data, 'ff_vc1_pquant_table', 'uint8_t', 'kPquantTable', [3, 32])
    table(data, 'ff_wmv3_dc_scale_table', 'uint8_t', 'kDcScale', [32])
    table(data, 'ff_vc1_dqscale', 'int32_t', 'kDqScale', [63], 8)
    # BFRACTION: the table of the standard (denominator 256), after the #else.
    bf = data[data.index('#else', data.index('B_FRACTION_DEN == 840')):]
    emit(out, 'int16_t', 'kBfraction', numbers(find_array(bf, 'ff_vc1_bfraction_lut')), [23])
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


main()
