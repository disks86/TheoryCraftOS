#!/usr/bin/env bash
# Compiles the Direct3D 9 shaders tests/SmToDxbcTest.cpp translates (tests/data/d3d9/*.hlsl) to the token streams that are checked in beside them
# (<name>.<profile>.bin). Run it after changing one of the sources; the tests do not need it. Uses scripts/hlsl-compile.sh (mingw and wine).
# It also writes them as arrays for the program that draws with them on the running system (tests/windows/d3d9test_shaders.h).
# Usage: scripts/gen-d3d9-test-shaders.sh
set -euo pipefail
cd "$(dirname "$0")/.."
for spec in "vs_basic vs_1_1" "vs_basic vs_2_0" "vs_basic vs_3_0" "vs_math vs_2_0" "vs_math vs_3_0" "ps_tex ps_2_0" "ps_tex ps_3_0" "ps_math ps_2_0" "ps_math ps_3_0" "ps_cube ps_2_0" "ps_volume ps_2_0"; do
  set -- $spec
  scripts/hlsl-compile.sh "tests/data/d3d9/$1.hlsl" main "$2" "tests/data/d3d9/$1.$2.bin"
  echo "wrote tests/data/d3d9/$1.$2.bin"
done
python3 - <<'PY'
import glob, os, struct
out = ['/* Generated by scripts/gen-d3d9-test-shaders.sh from tests/data/d3d9: the shaders tests/windows/d3d9test.c draws with. Do not edit. */']
for path in sorted(glob.glob('tests/data/d3d9/*.bin')):
    data = open(path, 'rb').read()
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    name = os.path.basename(path)[:-4].replace('.', '_')
    out.append('static const DWORD g_%s[%d] = {' % (name, len(words)))
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x%08X' % w for w in words[i:i + 8]) + ',')
    out.append('};')
open('tests/windows/d3d9test_shaders.h', 'w').write('\n'.join(out) + '\n')
print('wrote tests/windows/d3d9test_shaders.h')
PY
