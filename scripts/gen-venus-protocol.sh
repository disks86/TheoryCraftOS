# Regenerates src/Vulkan/venus-protocol: the driver side of the Venus protocol (the encoders and decoders of every Vulkan command, MIT, generated by
# venus-protocol's vn_protocol.py from its vk.xml), with the includes made freestanding (the driver has no C library: vk_venus.inc defines what they used).
#
# Usage: scripts/gen-venus-protocol.sh <venus-protocol checkout>   (https://gitlab.freedesktop.org/virgl/venus-protocol, tag v1.1.3: what Mesa pins)
# Needs python3 with mako (a venv: python3 -m venv v && v/bin/pip install mako; PYTHON=v/bin/python).
set -euo pipefail
src=${1:?usage: gen-venus-protocol.sh <venus-protocol checkout>}
src=$(cd "$src" && pwd)
here=$(cd "$(dirname "$0")/.." && pwd)
out=$here/src/Vulkan/venus-protocol
python=${PYTHON:-python3}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
version=$(cd "$src" && (git describe --tags 2>/dev/null || basename "$src"))
printf '/* venus-protocol %s, generated by scripts/gen-venus-protocol.sh */\n' "$version" > "$work/banner"
(cd "$src" && PYTHONPATH="$src" "$python" vn_protocol.py --outdir "$work" --banner "$work/banner")
mkdir -p "$out"
for f in "$work"/vn_protocol_driver*.h; do
  # (no C library headers: the driver's own definitions come first, from vk_venus.inc)
  sed -e 's|^#include <vulkan/vulkan.h>|#include "../khronos/vulkan/vulkan_core.h"|' \
      -e 's|^#include <stdlib.h>||' -e 's|^#include <string.h>||' -e 's|^#include <assert.h>||' "$f" > "$out/$(basename "$f")"
done
echo "wrote $(ls "$out"/vn_protocol_driver*.h | wc -l) headers to $out ($version)"
