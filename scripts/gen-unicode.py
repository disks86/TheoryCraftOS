"""Writes src/Windows/ntdll/unidata.inc: the Unicode data of the string functions of ntdll (and kernel32 on top of them) (normalization: combining classes, decompositions and compositions), made with
the unicodedata module of Python.

Usage: scripts/gen-unicode.py
"""
import os
import unicodedata as ud

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX = 0x110000


def is_hangul(c):
    return 0xAC00 <= c <= 0xD7A3


def full(c, compat):
    """The complete decomposition of a character without Hangul syllables (those are done by an algorithm)."""
    d = ud.normalize("NFKD" if compat else "NFD", chr(c))
    return [ord(x) for x in d]


THAI_ALPHA = {0xe31, 0xe34, 0xe35, 0xe36, 0xe37, 0xe38, 0xe39, 0xe3a, 0xe47, 0xe48, 0xe49, 0xe4a, 0xe4b, 0xe4c, 0xe4d, 0xe4e, 0x1885, 0x1886}
BIDI = {"L": 1, "R": 2, "AL": 2, "EN": 3, "ES": 4, "ET": 5, "AN": 6, "CS": 7, "B": 8, "S": 9, "WS": 10, "ON": 11}


def ctype(c):
    """The three GetStringType classifications (CT_CTYPE1, 2 and 3) of a character of the BMP, as Windows gives them."""
    ch = chr(c)
    cat = ud.category(ch)
    if cat in ("Cn", "Cs") or c in (0xFFFE, 0xFFFF) or 0xFDD0 <= c <= 0xFDEF:
        return 0, 0, 0x800 if 0xD800 <= c < 0xDC00 else 0x1000 if 0xDC00 <= c < 0xE000 else 0
    c1 = 0x200
    if cat == "Lu": c1 |= 0x1 | 0x100
    elif cat == "Ll": c1 |= 0x2 | 0x100
    elif cat == "Lt": c1 |= 0x1 | 0x2 | 0x100
    elif cat in ("Lm", "Lo", "Nl"): c1 |= 0x100
    if c in (0x2071, 0x207F): c1 |= 0x2
    if c in THAI_ALPHA: c1 |= 0x100
    if cat == "Nd" or c in (0xB2, 0xB3, 0xB9): c1 |= 0x4
    if cat in ("Zs", "Zl", "Zp") or c in (0x9, 0xA, 0xB, 0xC, 0xD, 0x85): c1 |= 0x8
    if cat in ("Cc", "Cf"): c1 |= 0x20
    if cat == "Zs" or c in (0x9, 0xFEFF): c1 |= 0x40
    if cat in ("Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po") or (c < 0x100 and cat in ("Sc", "Sm", "Sk", "So", "No") and not c1 & 0x4) or c == 0xAD: c1 |= 0x10
    if c < 0x80 and chr(c) in "0123456789abcdefABCDEF": c1 |= 0x80
    c2 = BIDI.get(ud.bidirectional(ch), 0)
    c3 = 0
    if cat in ("Mn", "Me"): c3 |= 0x1
    if cat in ("Sk", "Lm") and c < 0x370 or 0x300 <= c <= 0x36F: c3 |= 0x2
    if cat in ("Mc",) or c in THAI_ALPHA and cat == "Mn": c3 |= 0x4
    if cat in ("Sc", "Sm", "Sk", "So"): c3 |= 0x8
    if 0x30A0 <= c <= 0x30FF or 0x31F0 <= c <= 0x31FF or 0xFF66 <= c <= 0xFF9F: c3 |= 0x10
    if 0x3040 <= c <= 0x309F: c3 |= 0x20
    if 0xFF61 <= c <= 0xFFDC or 0xFFE8 <= c <= 0xFFEE: c3 |= 0x40
    if 0xFF01 <= c <= 0xFF60 or 0xFFE0 <= c <= 0xFFE6: c3 |= 0x80
    if 0x3400 <= c <= 0x4DBF or 0x4E00 <= c <= 0x9FFF or 0xF900 <= c <= 0xFAFF: c3 |= 0x100
    if c == 0x640: c3 |= 0x200
    if c1 & 0x100: c3 |= 0x8000
    return c1, c2, c3


def write_ctype():
    runs = []
    for c in range(0x10000):
        t = ctype(c)
        if runs and runs[-1][1] + 1 == c and runs[-1][2] == t:
            runs[-1][1] = c
        else:
            runs.append([c, c, t])
    out = ["/* Generated by scripts/gen-unicode.py (Unicode %s): the character classes of GetStringType. Not compiled by itself. */" % ud.unidata_version, ""]
    out.append("static const struct { WORD first, last, c1, c2, c3; } k_ctype_runs[%d] = {" % len(runs))
    out.append(",".join("{0x%x,0x%x,0x%x,%d,0x%x}" % (r[0], r[1], r[2][0], r[2][1], r[2][2]) for r in runs))
    out.append("};")
    out.append("")
    path = os.path.join(root, "src", "Windows", "kernel32", "ctype_data.inc")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d bytes)" % (path, os.path.getsize(path)))


def main():
    write_ctype()
    out = ["/* Generated by scripts/gen-unicode.py (Unicode %s): the Unicode data of ntdll.dll. Not compiled by itself. */" % ud.unidata_version, ""]
    # combining classes as runs
    runs = []
    for c in range(MAX):
        ccc = ud.combining(chr(c)) if not 0xD800 <= c < 0xE000 else 0
        if ccc:
            if runs and runs[-1][1] + 1 == c and runs[-1][2] == ccc:
                runs[-1][1] = c
            else:
                runs.append([c, c, ccc])
    out.append("static const struct { DWORD first, last; BYTE ccc; } uni_ccc[%d] = {" % len(runs))
    out.append(",".join("{0x%x,0x%x,%d}" % tuple(r) for r in runs))
    out.append("};")
    for name, compat in (("canonical", False), ("compat", True)):
        entries = []
        pool = []
        for c in range(0x80, MAX):
            if is_hangul(c) or 0xD800 <= c < 0xE000:
                continue
            d = full(c, compat)
            if d != [c]:
                entries.append((c, len(pool), len(d)))
                pool.extend(d)
        out.append("static const DWORD uni_%s_pool[%d] = {%s};" % (name, len(pool), ",".join("0x%x" % x for x in pool)))
        out.append("static const struct { DWORD cp; WORD offset; BYTE length; } uni_%s[%d] = {" % (name, len(entries)))
        out.append(",".join("{0x%x,%d,%d}" % e for e in entries))
        out.append("};")
    # compositions: the canonical pairs that are not excluded (NFC of the pair gives the character back)
    pairs = []
    for c in range(0x80, MAX):
        if is_hangul(c) or 0xD800 <= c < 0xE000:
            continue
        d = ud.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(c):
            pairs.append((parts[0], parts[1], c))
    pairs.sort()
    out.append("static const struct { DWORD first, second, composed; } uni_compose[%d] = {" % len(pairs))
    out.append(",".join("{0x%x,0x%x,0x%x}" % p for p in pairs))
    out.append("};")
    out.append("")
    path = os.path.join(root, "src", "Windows", "ntdll", "unidata.inc")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d bytes)" % (path, os.path.getsize(path)))


main()
