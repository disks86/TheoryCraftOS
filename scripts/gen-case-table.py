"""Writes src/Windows/ntdll/casetab.inc: the simple upper and lower case mappings of the Basic Multilingual Plane, as ranges {first, count, delta, step}, from the
Unicode database of the Python that runs this script. ntdll.dll's RtlUpcaseUnicodeChar and RtlDowncaseUnicodeChar look the characters up in them.

Usage: scripts/gen-case-table.py
"""
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Mappings that cross scripts and that Windows does not make (dotless i, long s, the Kelvin and Angstrom signs map to their letters in Unicode but not in NTFS).
SKIP = {0x131, 0x17F, 0x212A, 0x212B, 0x130}


def simple(cp, lower):
    if 0xD800 <= cp <= 0xDFFF or cp in SKIP:
        return cp
    c = chr(cp)
    m = c.lower() if lower else c.upper()
    if len(m) != 1:
        return cp
    r = ord(m)
    if r > 0xFFFF or ord(m) in SKIP:
        return cp
    return r


def ranges(lower):
    delta = [simple(cp, lower) - cp for cp in range(0x10000)]
    out = []
    cp = 0
    while cp < 0x10000:
        if delta[cp] == 0:
            cp += 1
            continue
        d = delta[cp]
        n1 = 1
        while cp + n1 < 0x10000 and delta[cp + n1] == d:
            n1 += 1
        n2 = 1
        while cp + 2 * n2 < 0x10000 and delta[cp + 2 * n2] == d and delta[cp + 2 * n2 - 1] == 0:
            n2 += 1
        if n1 >= n2:
            out.append((cp, n1, d, 1))
            cp += n1
        else:
            out.append((cp, n2, d, 2))
            cp += 2 * n2 - 1
    return out


