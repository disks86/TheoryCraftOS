#!/usr/bin/env bash
# Compiles the vertex shader of d3d9.dll's fixed-function pipeline (src/Windows/d3d9/ff_vs.hlsl) and writes it as a C array to
# src/Windows/d3d9/shaders.inc, which is checked in: the build does not need this script. Run it after changing the file. (The pixel shaders
# of that pipeline are made as it runs, one for each set-up of the texture stages: src/Windows/d3d9/ff_stages.h.)
# The compiler is scripts/hlsl-compile.sh (Wine's d3dcompiler_47: it needs x86_64-w64-mingw32-gcc and wine on the machine).
# Usage: scripts/gen-d3d9-shaders.sh
set -euo pipefail
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
scripts/hlsl-compile.sh src/Windows/d3d9/ff_vs.hlsl main vs_4_0 "$work/ff_vs.dxbc"
python3 - "$work" src/Windows/d3d9/shaders.inc <<'PY'
import sys
out = ["/* Generated by scripts/gen-d3d9-shaders.sh from ff_vs.hlsl: do not edit. */"]
for name in ("ff_vs",):
    data = open("%s/%s.dxbc" % (sys.argv[1], name), "rb").read()
    out.append("static const unsigned char g_%s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
PY
echo "wrote src/Windows/d3d9/shaders.inc"
