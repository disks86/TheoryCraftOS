#!/usr/bin/env bash
# Compiles the two shaders of d3d9.dll's fixed-function pipeline (src/Windows/d3d9/ff_vs.hlsl, ff_ps.hlsl) and writes them as C arrays to
# src/Windows/d3d9/shaders.inc, which is checked in: the build does not need this script. Run it after changing one of the two files.
# The compiler is the D3DCompile of Wine's d3dcompiler_47 (vkd3d-shader), called from a small program built with the mingw compiler - so it needs
# x86_64-w64-mingw32-gcc and wine on the machine. A d3dcompiler_47.dll next to the program must not be this project's (a stub).
# Usage: scripts/gen-d3d9-shaders.sh
set -euo pipefail
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cat > "$work/hc.c" <<'C'
#include <windows.h>
#include <stdio.h>
#include <d3dcompiler.h>
int main(int argc, char **argv) {
  static char source[1 << 16];
  if (argc < 5) return 2;
  FILE *f = fopen(argv[1], "rb");
  if (!f) return 3;
  const size_t n = fread(source, 1, sizeof source, f);
  fclose(f);
  ID3DBlob *code = NULL, *errors = NULL;
  const HRESULT hr = D3DCompile(source, n, argv[1], NULL, NULL, argv[2], argv[3], 0, 0, &code, &errors);
  if (errors) fprintf(stderr, "%.*s\n", (int)errors->lpVtbl->GetBufferSize(errors), (char *)errors->lpVtbl->GetBufferPointer(errors));
  if (FAILED(hr) || !code) return 1;
  f = fopen(argv[4], "wb");
  if (!f) return 4;
  fwrite(code->lpVtbl->GetBufferPointer(code), 1, code->lpVtbl->GetBufferSize(code), f);
  fclose(f);
  return 0;
}
C
x86_64-w64-mingw32-gcc -O1 -static -o "$work/hc.exe" "$work/hc.c" -ld3dcompiler_47
cp src/Windows/d3d9/ff_vs.hlsl src/Windows/d3d9/ff_ps.hlsl "$work/"
(cd "$work" && WINEDEBUG=-all wine hc.exe ff_vs.hlsl main vs_4_0 ff_vs.dxbc && WINEDEBUG=-all wine hc.exe ff_ps.hlsl main ps_4_0 ff_ps.dxbc)
python3 - "$work" src/Windows/d3d9/shaders.inc <<'PY'
import sys
out = ["/* Generated by scripts/gen-d3d9-shaders.sh from ff_vs.hlsl and ff_ps.hlsl: do not edit. */"]
for name in ("ff_vs", "ff_ps"):
    data = open("%s/%s.dxbc" % (sys.argv[1], name), "rb").read()
    out.append("static const unsigned char g_%s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
PY
echo "wrote src/Windows/d3d9/shaders.inc"
