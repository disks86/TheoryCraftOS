# Compiles the 3D test's Vulkan shaders (src/Desktop/CubeShaders/*.vert, *.frag) with glslc and writes their SPIR-V as word arrays into
# src/Desktop/CubeShaders/CubeSpirv.inc, which the kernel's cube renderer translates to DXBC at run time (as vulkan-1.dll does). Rerun after
# editing a shader: python3 scripts/gen-cube-spirv.py
import os
import struct
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "src", "Desktop", "CubeShaders")
SHADERS = [("kColoredVertexSpirv", "colored.vert"), ("kColoredFragmentSpirv", "colored.frag"),
           ("kTexturedVertexSpirv", "textured.vert"), ("kTexturedFragmentSpirv", "textured.frag")]


def compile_words(source):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "out.spv")
        subprocess.run(["glslc", "-O", "--target-env=vulkan1.0", "-o", out, os.path.join(DIR, source)], check=True)
        data = open(out, "rb").read()
    return struct.unpack("<%dI" % (len(data) // 4), data)


lines = ["// Generated by scripts/gen-cube-spirv.py from the shaders next to this file. Do not edit.", "#pragma once", "#include <stdint.h>", ""]
for name, source in SHADERS:
    words = compile_words(source)
    lines.append("// %s" % source)
    lines.append("constexpr uint32_t %s[%d] = {" % (name, len(words)))
    for i in range(0, len(words), 10):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 10]) + ",")
    lines.append("};")
    lines.append("")
open(os.path.join(DIR, "CubeSpirv.inc"), "w").write("\n".join(lines))
