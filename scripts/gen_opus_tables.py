#!/usr/bin/env python3
"""Extracts the normative constant tables of Opus (CELT and SILK) from a libopus source tree (BSD-3-Clause, Xiph.Org / Skype /
Broadcom) into src/Media/Audio/OpusCeltTables.inc and OpusSilkTables.inc, flattened to one-dimensional arrays.

Usage: scripts/gen_opus_tables.py <libopus-checkout> [output-directory]      (written against libopus v1.4)
"""
import re, sys, os

root = sys.argv[1]
out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'src', 'Media', 'Audio')

TYPES = {'unsigned char': 'uint8_t', 'signed char': 'int8_t', 'opus_int16': 'int16_t', 'opus_int32': 'int32_t', 'opus_uint32': 'uint32_t',
         'opus_val16': 'float', 'opus_int8': 'int8_t', 'opus_uint8': 'uint8_t', 'int': 'int', 'char': 'int8_t', 'float': 'float'}

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)

def find(path, name):
    src = strip_comments(open(os.path.join(root, path)).read())
    # the whole preprocessed-out #if/#else structure is handled by the caller picking the right file and name
    m = re.search(r'(?:static\s+)?(?:const\s+)?((?:unsigned |signed )?\w+)\s+(?:const\s+)?' + re.escape(name) + r'\s*((?:\[[^\]]*\]\s*)*)=\s*\{(.*?)\}\s*;', src, flags=re.S)
    if not m:
        raise SystemExit('table %s not found in %s' % (name, path))
    ctype = m.group(1)
    if m.group(1) == 'unsigned' or m.group(1) == 'signed':
        raise SystemExit('type parse ' + name)
    body = m.group(3)
    body = re.sub(r'#\w+[^\n]*', '', body)
    items = [x.strip() for x in re.split(r'[,{}\s]+', body) if x.strip()]
    return ctype, items

tables = [
    # (c++ name, file, c name, override type)
    ('kCeltLogN', 'celt/static_modes_float.h', 'logN400', None),
    ('kCeltCacheIndex', 'celt/static_modes_float.h', 'cache_index50', None),
    ('kCeltCacheBits', 'celt/static_modes_float.h', 'cache_bits50', None),
    ('kCeltCacheCaps', 'celt/static_modes_float.h', 'cache_caps50', None),
    ('kCeltEBands', 'celt/modes.c', 'eband5ms', 'int16_t'),
    ('kCeltBandAllocation', 'celt/modes.c', 'band_allocation', 'uint8_t'),
    ('kCeltEProbModel', 'celt/quant_bands.c', 'e_prob_model', 'uint8_t'),
    ('kCeltTfSelect', 'celt/celt.c', 'tf_select_table', 'int8_t'),
    ('kCeltOrdery', 'celt/bands.c', 'ordery_table', 'int'),
    ('kCeltLog2Frac', 'celt/rate.c', 'LOG2_FRAC_TABLE', 'uint8_t'),
    ('kCeltTrimIcdf', 'celt/celt.h', 'trim_icdf', 'uint8_t'),
    ('kCeltSpreadIcdf', 'celt/celt.h', 'spread_icdf', 'uint8_t'),
    ('kCeltTapsetIcdf', 'celt/celt.h', 'tapset_icdf', 'uint8_t'),
]
# silk tables are appended by gen_opus_silk below when the file list exists
silk_files = [f for f in os.listdir(os.path.join(root, 'silk')) if f.startswith('tables_') and f.endswith('.c')] + ['table_LSF_cos.c', 'pitch_est_tables.c', 'resampler_rom.c']

header = ['// Generated by scripts/gen_opus_tables.py from libopus v1.4 (BSD-3-Clause, (c) Xiph.Org Foundation, Skype Limited, Octasic,',
         '// Jean-Marc Valin, Timothy B. Terriberry, CSIRO, Gregory Maxwell, Mark Borgerding, Erik de Castro Lopo, Broadcom). Do not edit.', '']
lines = list(header)
for cname, path, name, override in tables:
    ctype, items = find(path, name)
    t = override or TYPES.get(ctype)
    if t is None:
        raise SystemExit('type %s of %s' % (ctype, name))
    lines.append('static const %s %s[%d] = {%s};' % (t, cname, len(items), ', '.join(items)))
celt_lines = lines
lines = list(header)
lines.append('// Values of the macros the SILK tables are written with (silk/define.h).')
lines.append('static const int16_t OFFSET_UVL_Q10 = 100, OFFSET_UVH_Q10 = 240, OFFSET_VL_Q10 = 32, OFFSET_VH_Q10 = 100;')
silk_names = []
for f in sorted(silk_files):
    src = strip_comments(open(os.path.join(root, 'silk', f)).read())
    for m in re.finditer(r'const\s+((?:unsigned |signed )?\w+)\s+(silk_\w+)\s*((?:\[[^\]]*\]\s*)*)=\s*\{(.*?)\}\s*;', src, flags=re.S):
        ctype, name, dims, body = m.groups()
        body = re.sub(r'#\w+[^\n]*', '', body)
        items = [x.strip() for x in re.split(r'[,{}\s]+', body) if x.strip()]
        t = TYPES.get(ctype)
        if t is None:
            continue
        if any(re.match(r'[A-Za-z_]', x) for x in items) and name != 'silk_Quantization_Offsets_Q10':
            continue  # written with macros of the encoder (silk/pitch_est_defines.h)
        lines.append('static const %s k_%s[%d] = {%s};' % (t, name, len(items), ', '.join(items)))
        silk_names.append(name)
open(os.path.join(out_dir, 'OpusCeltTables.inc'), 'w').write('\n'.join(celt_lines) + '\n')
open(os.path.join(out_dir, 'OpusSilkTables.inc'), 'w').write('\n'.join(lines) + '\n')
print('wrote', len(celt_lines), 'celt and', len(silk_names), 'silk tables')
