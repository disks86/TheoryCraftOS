#!/usr/bin/env python3
"""Turns an IVF file of AV1 or VP9 packets into a self-test stream include (AmdVcnSelfTestAv1Stream.inc, AmdVcnSelfTestVp9Stream.inc): the packets back to back as a C++
array, and where each one ends.

  gen_ivf_selftest_inc.py av1|vp9 stream.ivf out.inc

The IVF file is untrusted input only in the sense that it is read, never executed.
"""
import struct
import sys


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ('av1', 'vp9'):
        sys.exit(__doc__)
    codec = sys.argv[1]
    with open(sys.argv[2], 'rb') as f:
        d = f.read()
    if d[:4] != b'DKIF' or d[8:12] != {'av1': b'AV01', 'vp9': b'VP90'}[codec]:
        sys.exit('not an IVF file of that codec')
    pos = struct.unpack('<H', d[6:8])[0]
    stream, ends = bytearray(), []
    while pos + 12 <= len(d):
        size = struct.unpack('<I', d[pos:pos + 4])[0]
        unit = d[pos + 12:pos + 12 + size]
        if len(unit) != size:
            sys.exit('truncated IVF file')
        stream += unit
        ends.append(len(stream))
        pos += 12 + size
    width, height = struct.unpack('<HH', d[12:16])
    name = codec.capitalize()
    rows = ['    ' + ', '.join('0x%02X' % b for b in stream[i:i + 24]) + ',' for i in range(0, len(stream), 24)]
    out = ('// Generated by scripts/gen_ivf_selftest_inc.py (see scripts/gen_%s_selftest.sh): a %d x %d stream of %d packets (hidden frames included), the stream the VCN %s self-test\n'
           '// has the engine decode. Do not edit by hand.\n'
           'constexpr uint32_t k%sSelfTestPictures = %d;\n'
           'constexpr uint32_t k%sSelfTestSize = %d;\n'
           'constexpr uint64_t k%sSelfTestEnds[%d] = {%s};\n'
           'constexpr uint8_t k%sSelfTestStream[%d] = {\n%s\n};\n') % (
        codec, width, height, len(ends), codec.upper(), name, len(ends), name, width, name, len(ends), ', '.join(str(e) for e in ends), name, len(stream), '\n'.join(rows))
    with open(sys.argv[3], 'w') as f:
        f.write(out)


main()
