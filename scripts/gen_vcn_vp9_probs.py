#!/usr/bin/env python3
"""Generates AmdVcnVp9Probs.inc: the default VP9 probability table in the layout the VCN firmware reads (rvcn_dec_vp9_probs_t), which starts the decoder's context buffer
and the table buffer. The tables and the function that fills the structure are Mesa's (vl_probs_table.h and fill_probs_table of radeon_vcn_dec.c; Copyright
Advanced Micro Devices, Inc. and others; MIT license): they are compiled with a few lines of main() and the program's output is stored.

  gen_vcn_vp9_probs.py out.inc radeon_vcn_dec.h vl_probs_table.h radeon_vcn_dec.c

The inputs are untrusted: they are only compiled (never run on their own), in a temporary directory.
"""
import os
import subprocess
import sys
import tempfile

MAIN = r'''
int main(int argc, char **argv) {
  rvcn_dec_vp9_probs_t probs;
  memset(&probs, 0, sizeof probs);
  fill_probs_table(&probs);
  FILE *f = fopen(argv[1], "wb");
  fwrite(&probs, 1, sizeof probs, f);
  fclose(f);
  return 0;
}
'''


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    out_path, header, tables, source = sys.argv[1:]
    h = open(header).read()
    a = h.index('typedef struct rvcn_dec_vp9_nmv_ctx_mask_s')
    b = h.index('} rvcn_dec_vp9_probs_t;') + len('} rvcn_dec_vp9_probs_t;')
    c = open(source).read()
    fa = c.index('static void fill_probs_table')
    fb = c.index('\n}\n', fa) + 3
    program = '#include <stdint.h>\n#include <stdio.h>\n#include <string.h>\n' + open(tables).read() + '\n' + h[a:b] + '\n' + c[fa:fb] + MAIN
    with tempfile.TemporaryDirectory() as tmp:
        src, exe, blob = (os.path.join(tmp, n) for n in ('probs.c', 'probs', 'probs.bin'))
        open(src, 'w').write(program)
        subprocess.check_call(['gcc', '-std=gnu11', '-w', '-o', exe, src])
        subprocess.check_call([exe, blob])
        data = open(blob, 'rb').read()
    lines = ['// Generated by scripts/gen_vcn_vp9_probs.py from Mesa\'s vl_probs_table.h and radeon_vcn_dec.c (Copyright Advanced Micro Devices, Inc. and others; MIT license).',
             '// The default VP9 probabilities in the firmware\'s layout (rvcn_dec_vp9_probs_t). Do not edit by hand.',
             'constexpr uint8_t kVp9DefaultProbs[%d] = {' % len(data)]
    for k in range(0, len(data), 24):
        lines.append('    ' + ', '.join('0x%02X' % v for v in data[k:k + 24]) + ',')
    lines.append('};')
    open(out_path, 'w').write('\n'.join(lines) + '\n')


main()
