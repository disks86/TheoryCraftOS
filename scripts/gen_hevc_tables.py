#!/usr/bin/env python3
"""Makes H265Transform.inc, the 32x32 transform matrix of H.265 (transMatrix of 8.6.4.2), from a copy of FFmpeg's libavcodec/hevcdsp.c (the array `transform`).

  gen_hevc_tables.py out.inc hevcdsp.c
"""
import re
import sys

out, path = sys.argv[1], sys.argv[2]
t = open(path).read()
a = t.index('static const int8_t transform[32][32]')
b = t.index('};', a)
nums = [int(x) for x in re.findall(r'-?\d+', t[a + len('static const int8_t transform[32][32]'):b])]
assert len(nums) == 1024, len(nums)
lines = ['// Generated by scripts/gen_hevc_tables.py: the 32x32 transform matrix of ITU-T H.265 (8.6.4.2, transMatrix): row k is basis function k; the smaller transforms',
         '// use every (32/N)-th row. Do not edit by hand.', '{']
for r in range(32):
    lines.append('  {' + ', '.join(str(x) for x in nums[r * 32:(r + 1) * 32]) + '},')
lines.append('}')
open(out, 'w').write('\n'.join(lines) + '\n')
