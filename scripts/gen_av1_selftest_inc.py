#!/usr/bin/env python3
"""Turns an IVF file of AV1 temporal units into AmdVcnSelfTestAv1Stream.inc: the temporal units back to back as a C++ array, and where each one ends.

  gen_av1_selftest_inc.py stream.ivf out.inc

The IVF file is untrusted input only in the sense that it is read, never executed.
"""
import struct
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    with open(sys.argv[1], 'rb') as f:
        d = f.read()
    if d[:4] != b'DKIF' or d[8:12] != b'AV01':
        sys.exit('not an AV1 IVF file')
    pos = struct.unpack('<H', d[6:8])[0]
    stream, ends = bytearray(), []
    while pos + 12 <= len(d):
        size = struct.unpack('<I', d[pos:pos + 4])[0]
        unit = d[pos + 12:pos + 12 + size]
        if len(unit) != size:
            sys.exit('truncated IVF file')
        stream += unit
        ends.append(len(stream))
        pos += 12 + size
    width, height = struct.unpack('<HH', d[12:16])
    rows = ['    ' + ', '.join('0x%02X' % b for b in stream[i:i + 24]) + ',' for i in range(0, len(stream), 24)]
    out = ('// Generated by scripts/gen_av1_selftest_inc.py (see scripts/gen_av1_selftest.sh): a %d x %d stream of %d temporal units made by libaom (hidden frames, show_existing_frame),\n'
           '// the stream the VCN AV1 self-test has the engine decode. Do not edit by hand.\n'
           'constexpr uint32_t kAv1SelfTestPictures = %d;\n'
           'constexpr uint32_t kAv1SelfTestSize = %d;\n'
           'constexpr uint64_t kAv1SelfTestEnds[%d] = {%s};\n'
           'constexpr uint8_t kAv1SelfTestStream[%d] = {\n%s\n};\n') % (width, height, len(ends), len(ends), width, len(ends), ', '.join(str(e) for e in ends), len(stream), '\n'.join(rows))
    with open(sys.argv[2], 'w') as f:
        f.write(out)


main()
