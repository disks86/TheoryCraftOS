"""Writes src/Windows/d3d8/d3d9_abi.h: the interfaces of Direct3D 9 (their vtables, method by method) and the structures d3d8.dll hands to d3d9.dll, in a
form that can be included together with mingw's d3d8.h.

d3d8.dll is a layer on d3d9.dll's COM interfaces, but d3d8.h and d3d9.h cannot be in one translation unit: they define the same enumerations and structures
(D3DFORMAT, D3DPRESENT_PARAMETERS, D3DSURFACE_DESC ...) with other members. The interfaces are read from mingw's d3d9.h; a structure of Direct3D 9 whose name
Direct3D 8 also uses with another layout gets the suffix 9 (D3DPRESENT_PARAMETERS9, D3DSURFACE_DESC9, D3DVOLUME_DESC9), the ones Direct3D 8 has with the same
layout under its own name are named so (D3DVIEWPORT9 -> D3DVIEWPORT8 ...), and the enumerations Direct3D 8 lacks are copied.

    python3 scripts/gen-d3d9-abi.py
"""
import os
import re

INC = '/usr/x86_64-w64-mingw32/include/'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'Windows', 'd3d8', 'd3d9_abi.h')

d3d9 = open(INC + 'd3d9.h').read()
types = open(INC + 'd3d9types.h').read()
caps = open(INC + 'd3d9caps.h').read()

INTERFACES = ['IDirect3D9', 'IDirect3DVolume9', 'IDirect3DSwapChain9', 'IDirect3DResource9', 'IDirect3DSurface9', 'IDirect3DVertexBuffer9', 'IDirect3DIndexBuffer9',
              'IDirect3DBaseTexture9', 'IDirect3DCubeTexture9', 'IDirect3DTexture9', 'IDirect3DVolumeTexture9', 'IDirect3DVertexDeclaration9',
              'IDirect3DVertexShader9', 'IDirect3DPixelShader9', 'IDirect3DStateBlock9', 'IDirect3DQuery9', 'IDirect3DDevice9']

# Direct3D 9 type -> what it is called here
RENAME = {
    'D3DPRESENT_PARAMETERS': 'D3DPRESENT_PARAMETERS9',
    'D3DSURFACE_DESC': 'D3DSURFACE_DESC9',
    'D3DVOLUME_DESC': 'D3DVOLUME_DESC9',
    'D3DVIEWPORT9': 'D3DVIEWPORT8',
    'D3DMATERIAL9': 'D3DMATERIAL8',
    'D3DLIGHT9': 'D3DLIGHT8',
    'D3DCLIPSTATUS9': 'D3DCLIPSTATUS8',
    'D3DQUERYTYPE': 'DWORD',
}


def rename(text):
    for a, b in RENAME.items():
        text = re.sub(r'\b%s\b' % a, b, text)
    return text


def methods(iface):
    m = re.search(r'DECLARE_INTERFACE_IID_\(%s,(\w+),"([-0-9a-f]+)"\)\s*\{(.*?)\};' % iface, d3d9, re.S)
    assert m, iface
    body = m.group(3)
    out = []
    for mm in re.finditer(r'STDMETHOD(_\(([^,]+),\s*(\w+)\s*\)|\((\w+)\))\s*\((.*?)\)\s*PURE;', body, re.S):
        if mm.group(4):
            ret, name = 'HRESULT', mm.group(4)
        else:
            ret, name = mm.group(2).strip(), mm.group(3).strip()
        params = ' '.join(mm.group(5).split())
        params = re.sub(r'^THIS_\s*', '', params)
        params = '' if params == 'THIS' else params
        out.append((ret, name, params))
    return m.group(2), m.group(3) and m.group(2), out


def guid(iface):
    m = re.search(r'DEFINE_GUID\(IID_%s,\s*([^)]*)\);' % iface, d3d9)
    assert m, iface
    return ' '.join(m.group(1).split())


def struct(text, name):
    m = re.search(r'typedef struct _%s \{.*?\} [^;]*;' % name, text, re.S)
    assert m, name
    return m.group(0)


def enum(text, name):
    m = re.search(r'typedef enum _%s \{.*?\} %s;' % (name, name), text, re.S)
    assert m, name
    return re.sub(r'#if.*?\n|#endif.*?\n', '', m.group(0))


lines = ['/* Generated by scripts/gen-d3d9-abi.py from mingw-w64\'s d3d9.h: do not edit.',
         ' * The interfaces of Direct3D 9 and the structures that differ from Direct3D 8\'s, to be included after <d3d8.h> (see the script). */',
         '#ifndef TCOS_D3D9_ABI_H', '#define TCOS_D3D9_ABI_H', '', '#ifdef __i386__', '#pragma pack(push,4)      /* (as d3d9types.h and d3d9caps.h have their structures in 32-bit programs) */', '#endif']
lines.append(rename(enum(types, 'D3DDECLUSAGE')))
lines.append(enum(types, 'D3DDECLMETHOD'))
lines.append(enum(types, 'D3DDECLTYPE'))
lines.append(enum(types, 'D3DSAMPLERSTATETYPE'))
lines.append(struct(types, 'D3DVERTEXELEMENT9'))
lines.append(struct(types, 'D3DADAPTER_IDENTIFIER9'))
lines.append(rename(struct(types, 'D3DPRESENT_PARAMETERS_')).replace('_D3DPRESENT_PARAMETERS_', '_D3DPRESENT_PARAMETERS9'))
lines.append(rename(struct(types, 'D3DSURFACE_DESC')).replace('_D3DSURFACE_DESC', '_D3DSURFACE_DESC9'))
lines.append(rename(struct(types, 'D3DVOLUME_DESC')).replace('_D3DVOLUME_DESC', '_D3DVOLUME_DESC9'))
lines.append(struct(caps, 'D3DVSHADERCAPS2_0'))
lines.append(struct(caps, 'D3DPSHADERCAPS2_0'))
lines.append(struct(caps, 'D3DCAPS9'))
lines.append('#ifdef __i386__')
lines.append('#pragma pack(pop)')
lines.append('#endif')
lines.append('')
for iface in INTERFACES:
    lines.append('typedef struct %s { const struct %sVtbl *lpVtbl; } %s;' % (iface, iface, iface))
lines.append('')
for iface in INTERFACES:
    lines.append('DEFINE_GUID(IID_%s, %s);' % (iface, guid(iface)))
lines.append('')
for iface in INTERFACES:
    _, _, ms = methods(iface)
    lines.append('typedef struct %sVtbl {' % iface)
    for ret, name, params in ms:
        p = rename(params)
        lines.append('  %s (STDMETHODCALLTYPE *%s)(%s *This%s);' % (rename(ret), name, iface, (', ' + p) if p else ''))
    lines.append('} %sVtbl;' % iface)
    lines.append('')
lines.append('typedef IDirect3D9 *(WINAPI *PFN_Direct3DCreate9)(UINT sdk_version);')
lines.append('')
lines.append('#endif')
text = '\n'.join(lines) + '\n'
open(OUT, 'w').write(text)
print('wrote', OUT)
