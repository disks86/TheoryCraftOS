#!/usr/bin/env python3
"""Compiles the LLVM IR shaders of tests/data/gcn/*.ll for Polaris with LLVM's AMDGPU back end (llc -mtriple=amdgcn -mcpu=polaris10) and writes their machine code to
tests/GcnLlvmShaders.inc, so that tests/GcnEmuTest.cpp can run what a real compiler made on the emulator and compare with the CPU: an oracle for the emulator's semantics that does not
come from the same head as the emulator.

  gen_gcn_llvm_shaders.py [llc] [llvm-objcopy]
"""
import glob
import os
import subprocess
import sys
import tempfile

LLC = sys.argv[1] if len(sys.argv) > 1 else 'llc'
OBJCOPY = sys.argv[2] if len(sys.argv) > 2 else 'llvm-objcopy'
out = ['// Generated by scripts/gen_gcn_llvm_shaders.py from tests/data/gcn/*.ll with llc. Do not edit.']
for path in sorted(glob.glob('tests/data/gcn/*.ll')):
    name = os.path.splitext(os.path.basename(path))[0]
    with tempfile.TemporaryDirectory() as d:
        obj, binary = os.path.join(d, 'a.o'), os.path.join(d, 'a.bin')
        subprocess.run([LLC, '-mtriple=amdgcn', '-mcpu=polaris10', '-filetype=obj', path, '-o', obj], check=True)
        subprocess.run([OBJCOPY, '-O', 'binary', '--only-section=.text', obj, binary], check=True)
        data = open(binary, 'rb').read()
        asm = subprocess.run([LLC, '-mtriple=amdgcn', '-mcpu=polaris10', path, '-o', '-'], check=True, capture_output=True, text=True).stdout
    data = data.rstrip(b'\x00') if len(data) % 4 else data
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data) - len(data) % 4, 4)]
    # the code ends with s_endpgm (0xBF810000); what follows (padding) is dropped
    end = max(i for i, w in enumerate(words) if w == 0xBF810000)
    words = words[:end + 1]
    out.append('{"%s", {%s}},' % (name, ', '.join('0x%08Xu' % w for w in words)))
open('tests/GcnLlvmShaders.inc', 'w').write('\n'.join(out) + '\n')
print('gen_gcn_llvm_shaders: %d shaders' % (len(out) - 1))
